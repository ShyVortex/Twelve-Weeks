"""Builds src/ticker.js from tools/clan_story_data.py (English) and tools/clan_story_pl.py (Polish): the 2013 ticker pools (hungry / sick / healthy) and the name
pools, so the launcher can write the clan's status lines locally when the daemon has no feed lines for the player yet. Run from release/launcher:
python scripts/gen-ticker.py

Two globals come out, with the same keys:
  TICKER     English: hungry / sick / healthy (templates with {A}), notSera (substrings of the lines a Seraphite island does not have), namesW / namesS, rare
  TICKER_PL  Polish, the same keys, parallel lists (entry i of TICKER_PL.sick is the translation of entry i of TICKER.sick), plus
             gender = { name: "m" | "f" | "n" }  the grammatical gender of every name in namesW / namesS
Polish templates carry gender switches {A?m-form|f-form} (e.g. "{A} zachorował{A?|a} na botulizm" - empty masculine ending); fill a template of either
language with  tickerFill(template, name, gender)  (also generated here): it replaces {A} and resolves {A?..|..} ("n" takes the masculine form).
TICKER_PL.notSera holds the Polish substrings: filtering a Polish pool with them drops exactly the same entries as filtering the English pool with TICKER.notSera.
"""
import json, os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "..", "tools"))
import clan_story_data as D
import clan_story_pl as PL

first = [n for n in D.FIRST_2013 if n not in D.NEUTRAL_2013]
names_w = first + [n for n, g in D.EXTRA_WLF]
names_s = [n for n, g in D.EXTRA_SERA] + first[:30]
gender = {}
for n in D.FIRST_2013:
    gender[n] = "n" if n in D.NEUTRAL_2013 else "f" if n in D.FEMALE_2013 else "m"
for n, g in D.EXTRA_WLF + D.EXTRA_SERA:
    gender[n] = g
data = {
    "hungry": D.TICKER_HUNGRY, "sick": D.TICKER_SICK, "healthy": D.TICKER_HEALTHY, "notSera": list(D.TICKER_NOT_SERA),
    "namesW": names_w, "namesS": names_s, "rare": D.TICKER_RARE_SICK,
}
data_pl = {
    "hungry": PL.TICKER_HUNGRY, "sick": PL.TICKER_SICK, "healthy": PL.TICKER_HEALTHY, "notSera": list(PL.TICKER_NOT_SERA),
    "namesW": names_w, "namesS": names_s, "rare": PL.TICKER_RARE_SICK,
    "gender": {n: gender[n] for n in sorted(set(names_w + names_s))},
}
for k in ("hungry", "sick", "healthy"):
    assert len(data[k]) == len(data_pl[k]), k
helper = """// tickerFill("{A} zachorował{A?|a} na botulizm", "Mara", "f") -> "Mara zachorowała na botulizm"; English templates only have {A}. gender "n" = masculine form.
function tickerFill(tpl, name, gender) {
  return String(tpl).replace(/\\{A\\?([^|{}]*)\\|([^|{}]*)\\}/g, (m, a, b) => (gender === 'f' ? b : a)).replace(/\\{A\\}/g, name);
}
"""
out = os.path.join(HERE, "..", "src", "ticker.js")
open(out, "w", encoding="utf-8", newline="\n").write(
    "// generated by scripts/gen-ticker.py from tools/clan_story_data.py + tools/clan_story_pl.py - do not edit\n"
    "const TICKER = " + json.dumps(data, ensure_ascii=False) + ";\n"
    "const TICKER_PL = " + json.dumps(data_pl, ensure_ascii=False) + ";\n" + helper)
print({k: len(v) for k, v in data.items()}, {k: len(v) for k, v in data_pl.items()})
