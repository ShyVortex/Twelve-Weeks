"""data/crate-slots.json (the ONE shared loot-slot layout of the No Return supply crate, edited in the SceneEditor) -> tools/ext/nrbox_slots.h.
  python tools/maps/crate_slots.py        # regenerate the header
The ext (nrbox.c) places box loot slot k at crate pos * R(box yaw) + slot position, rotated by box rotation * slot quat * (optional kind_rot)."""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "data", "crate-slots.json")
HEADER = os.path.join(os.path.dirname(HERE), "ext", "nrbox_slots.h")
KINDS = ["ammo", "ingredient", "throwable", "health", "melee"]
ROLES = {"item": 0, "melee": 1, "spare": 2}
DEFAULT_ROLE = {5: "melee", 4: "spare", 8: "spare", 9: "spare"}     # 0-based slot -> role when the json carries none (the original layout)


def role_of(i, s):
    return s.get("role") or DEFAULT_ROLE.get(i, "item")


def load():
    return json.load(open(SRC))


SLOT_MIN = (-0.555, 0.34, -0.206)      # inner volume of the crate (crate-local): lining footprint minus 2 cm, lining top .. rim (mirrors the editor, MapKit.SlotMin / SlotMax)
SLOT_MAX = (0.562, 0.49, 0.185)


def validate(d):
    bad = []
    for i, s in enumerate(d["slots"]):
        p = s["pos"]
        if any(p[k] < SLOT_MIN[k] - 1e-4 or p[k] > SLOT_MAX[k] + 1e-4 for k in range(3)):
            bad.append(f"slot {i + 1} at {p} is outside the crate (x {SLOT_MIN[0]}..{SLOT_MAX[0]}, y {SLOT_MIN[1]}..{SLOT_MAX[1]}, z {SLOT_MIN[2]}..{SLOT_MAX[2]})")
    if bad:
        raise SystemExit("crate-slots.json: " + "; ".join(bad))


def write_header(d=None):
    d = d or load()
    sl = d["slots"]
    assert len(sl) == 12, "the crate has exactly 12 loot slots"
    validate(d)
    L = ["// generated by tools/maps/crate_slots.py from tools/maps/data/crate-slots.json - the shared loot-slot layout of the NR supply crate (crate-local, y up, front +z)",
         "static const float NRB_LOC[12][3] = {"]
    for s in sl:
        L.append("    {%.4ff, %.4ff, %.4ff}," % tuple(s["pos"]))
    L += ["};", "static const float NRB_LQ[12][4] = {"]
    for s in sl:
        L.append("    {%.6ff, %.6ff, %.6ff, %.6ff}," % tuple(s.get("quat") or [0, 0, 0, 1]))
    L += ["};", "// slot roles: 0 item (upper half), 1 melee (the one melee slot), 2 spare (lower half; only with no melee / too many items)", "static const unsigned char NRB_ROLE[12] = {" + ", ".join(str(ROLES.get(role_of(i, s), 0)) for i, s in enumerate(sl)) + "};", "// extra rotation per item category (ammo, ingredient, throwable, health, melee); identity = none", "static const float NRB_KQ[5][4] = {"]
    kr = d.get("kind_rot") or {}
    for k in KINDS:
        L.append("    {%.6ff, %.6ff, %.6ff, %.6ff}," % tuple(kr.get(k) or [0, 0, 0, 1]))
    L.append("};")
    open(HEADER, "w", newline="\n").write("\n".join(L) + "\n")
    return HEADER


if __name__ == "__main__":
    print(write_header())
