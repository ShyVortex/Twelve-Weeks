"""Generates tools/ext/rszl_keys.h: every render-settings key the Supermarket's interior zone symbols (sp_lighting.h g_spl_reg) define, with its
outdoor value (*pat-rs-pat-cloudy* over *pat-rs-pat*) and its indoor value (*pat-rs-pat-supermarket-main-bld* over the outdoor one), for the ext's
RSZL logger (tools/ext/rszl.c: lighting keys the RSZ tracker does not list: hood light, runtime light bounce, probe blend, ambient scales ...).

  python tools/maps/gen_rszl.py
"""
import math, os, re, struct, sys
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, os.path.join(ROOT, "tools", "part1")); sys.path.insert(0, os.path.join(ROOT, "tools", "win"))
import p1_rsenv as rs  # noqa: E402
import rs_bisect  # noqa: E402

GB = rs_bisect.GB
names = rs_bisect.exe_names()
mods = {}
d = os.path.join(GB, "dc1", "render-settings")
for fn in os.listdir(d):
    if fn.endswith(".bin"):
        try:
            mods[fn] = rs.DcRs(open(os.path.join(d, fn), "rb").read())
        except Exception:
            pass


def rows(sym):
    h = rs.fnv(sym)
    for md in mods.values():
        if h in md.syms:
            out = {}
            for k, v, _ in md.syms[h]:
                fv, kind = struct.unpack("<fi", v)
                if kind == -1 and k not in out:
                    out[k] = fv
            return out
    return {}


syms = re.findall(r'"(\*[^"]+\*)"', open(os.path.join(ROOT, "tools", "ext", "sp_lighting.h")).read())
syms = [s for s in dict.fromkeys(syms)]
keys = {}
for s in syms:
    for k in rows(s):
        keys.setdefault(k, 0)
base, cloudy = rows("*pat-rs-pat*"), rows("*pat-rs-pat-cloudy*")
mainb, sideb = rows("*pat-rs-pat-supermarket-main-bld*"), rows("*pat-rs-pat-supermarket-side-blds*")
out_v = {k: cloudy.get(k, base.get(k, float("nan"))) for k in keys}
in_v = {k: mainb.get(k, sideb.get(k, out_v[k])) for k in keys}
f = lambda x: "NAN" if math.isnan(x) else "%.4ff" % x
o = ["// generated by tools/maps/gen_rszl.py - do not edit: interior-zone keys (hash, name, outdoor value, indoor main-bld value; NAN = no row)",
     "typedef struct { uint64_t id; const char *name; float out, in; } rszl_key;", "static const rszl_key g_rszl_keys[] = {"]
for k in sorted(keys, key=lambda k: names.get(k, "~%016x" % k)):
    o.append('  {0x%016xULL, "%s", %s, %s},' % (k, names.get(k, "%016x" % k), f(out_v[k]), f(in_v[k])))
o += ["};", "#define RSZL_N ((int)(sizeof g_rszl_keys / sizeof *g_rszl_keys))"]
open(os.path.join(ROOT, "tools", "ext", "rszl_keys.h"), "w", newline="\n").write("\n".join(o) + "\n")
print(len(keys), "keys from", len(syms), "symbols")
