FORMATION = [(0.0, 0.8), (-1.9, -0.7), (1.9, -0.7), (0.0, -2.3)]
FORMATION_NARROW = [(0.6, 1.6), (-0.6, 0.3), (0.6, -1.0), (-0.6, -2.3)]      # alleys / doorways: a zig-zag column


def xz(p):
    return (p[0], p[2])


def at(c, yaw, right, fwd):
    """world offset of (right, forward) for facing yaw (forward = (sin, cos))"""
    fx, fz = math.sin(yaw), math.cos(yaw)
    rx, rz = fz, -fx
    return (c[0] + rx * right + fx * fwd, c[2] + rz * right + fz * fwd)


