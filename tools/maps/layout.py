class _P:
    def __init__(self, pos, cov):
        self.pos, self.cov = pos, cov


def fine_flat(ctx, pos, rad, resp, intro, others):
    """flat (<= E.FLAT_MAX under the crate) spots on a 0.5 m lattice within rad of pos that keep the box rules"""
    grid, nav = ctx.grid, ctx.nav
    out = []
    n = int(rad / grid.CELL)
    for dx in range(-n, n + 1):
        for dz in range(-n, n + 1):
            if dx * dx + dz * dz > n * n:
                continue
            x, z = pos[0] + dx * grid.CELL, pos[2] + dz * grid.CELL
            g = grid.ground(x, z, pos[1], 1.0)
            if not g or g[1] not in ctx.play or abs(g[0] - pos[1]) > 0.4:      # same floor level, no stairs / ramps up or down
                continue
            p = (x, g[0], z)
            if nav.edge_clear(x, z, g[0]) < RULES["box_edge_clear"] or E.flat(grid, p) > E.FLAT_MAX:
                continue
            if any(math.dist(p, q) < 6.0 for q in resp) or any(math.dist(p, q) < 10.0 for q in intro):
                continue
            if any(math.dist(p, o["pos"]) < 11.0 for o in others):
                continue
            if any(math.hypot(x - ex, z - ez) < er for ex, ez, er in E.box_exclusions(ctx, seed_file(ctx.key))):
                continue
            out.append(_P(p, E.cover_score(E.cover(grid, p))))
    return out


