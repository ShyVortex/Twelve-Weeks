class Cand:
    __slots__ = ("pos", "poly", "edge", "open", "seen", "side", "da", "db", "cov", "inside", "vant", "land", "edgef", "ymark", "qmark", "floor")

    def __init__(self, pos, poly):
        self.pos = pos
        self.poly = poly
        self.floor = -1
        self.ymark = None
        self.qmark = None


def key_is_generated(ctx):
    """one-way-ground filtering applies to the generated (SP-section) maps, not to the hand placed pool maps"""
    return ctx.key not in POOL


def candidates(ctx, step=3.0, edge=1.5):
    nav, grid = ctx.nav, ctx.grid
    k = max(1, int(round(step / grid.CELL)))
    out = []
    mutual = W.mutual_region(ctx) if key_is_generated(ctx) else None     # no one-way ground (ledges): you can get there AND back
    for (ix, iz), cell in grid.cells.items():
        if ix % k or iz % k:
            continue
        for y, pi in cell:
            if pi not in ctx.play or nav.area[pi] < 1.2 or (mutual is not None and pi not in mutual):
                continue
            x, z = (ix + 0.5) * grid.CELL, (iz + 0.5) * grid.CELL
            if ctx.bounds and not ctx.inb(x, z):
                continue
            pos = (x, y, z)
            if ctx.blockers and any(math.dist(pos, b) < 3.0 for b in ctx.blockers):
                continue
            if any(nav_cut(x, z, c) < float(ctx.spec.get("cut_clear", 14.0)) for c in ctx.cuts):      # (compact multi-floor maps: spec "cut_clear")
                continue
            e = nav.edge_clear(x, z, y)
            if e < edge:
                continue
            c = Cand(pos, pi)
            c.edge = e
            out.append(c)
    return out


def nav_cut(x, z, c):
    return L.nav_plan.seg_dist_xz(x, z, (c["a"][0], 0, c["a"][1]), (c["b"][0], 0, c["b"][1]))


def openness(ctx, pos):
    """0..1: mean free run in 8 directions (cap 6 m), and at least 3 directions of 6 m (not a dead end / corner)"""
    runs = [ctx.grid.run(pos, i * math.pi / 4, 6.0) for i in range(8)]
    full = sum(1 for r in runs if r >= 6.0)
    return (sum(runs) / 48.0) * (1.0 if full >= 3 else 0.5)


# ---------------------------------------------------------------------------------------------- team starts
def fit_group(ctx, centre, yaw):
    """-> (score, [positions]) of the 4-spawn wedge at centre facing yaw, or None. Every spawn on walkable ground of the
    centre's floor, 0.8 m from the nav edge, 1.4 m apart."""
    nav, grid = ctx.nav, ctx.grid
    pts, narrow = None, 0.0
    for form, pen in ((FORMATION, 0.0), (FORMATION_NARROW, 2.0)):
        cand = []
        for r, f in form:
            x, z = at(centre, yaw, r, f)
            g = grid.ground(x, z, centre[1], 0.7)
            if g is None or g[1] not in ctx.play or nav.edge_clear(x, z, g[0]) < 0.6 or g[1] not in W.mutual_region(ctx) or \
                    (ctx.bounds and not ctx.inb(x, z)):
                cand = None
                break
            cand.append((x, g[0], z))
        if cand and all(math.dist(p, q) >= RULES["intro_group_min"] for i, p in enumerate(cand) for q in cand[i + 1:]):
            pts, narrow = cand, pen
            break
    if pts is None:
        return None
    fwd = min(grid.run(p, yaw, 10.0) for p in pts)
    back = grid.run(centre, yaw + math.pi, 8.0)
    # room around the group (the wide intro shot): walkable cells within 6 m
    room = 0
    for dx in range(-12, 13, 3):
        for dz in range(-12, 13, 3):
            if grid.ground(centre[0] + dx * 0.5, centre[2] + dz * 0.5, centre[1], 1.0):
                room += 1
    score = min(fwd, 10.0) + 0.4 * min(back, 8.0) + 0.1 * room - narrow
    if fwd < RULES["intro_fwd_clear"]:
        score -= 20
    return score, pts


def route_dir(ctx, a_poly, b_poly, ahead=16.0):
    """direction (yaw) from a along the shortest path toward b, looking `ahead` m along the path"""
    nav = ctx.nav
    d, pred = dijkstra_pred(nav, a_poly)
    if b_poly not in d:
        return None
    path = L.path_points(nav, pred, b_poly, a_poly)
    acc = 0.0
    for u, v in zip(path, path[1:]):
        acc += nav.adj[u][v]
        if acc >= ahead:
            c0, c1 = nav.cen[path[0]], nav.cen[v]
            return math.atan2(c1[0] - c0[0], c1[2] - c0[2])
    c0, c1 = nav.cen[path[0]], nav.cen[path[-1]]
    return math.atan2(c1[0] - c0[0], c1[2] - c0[2])


def best_group(ctx, centre, poly, toward_poly, radius=8.0):
    """search around centre (radius m, 2 m steps) for the best wedge, facing along the route to toward_poly (+-45 deg)"""
    nav, grid = ctx.nav, ctx.grid
    best = None
    seeds = [centre]
    for dx in range(-int(radius), int(radius) + 1, 2):
        for dz in range(-int(radius), int(radius) + 1, 2):
            if dx * dx + dz * dz <= radius * radius:
                g = grid.ground(centre[0] + dx, centre[2] + dz, centre[1], 0.7)
                if g and g[1] in ctx.play and nav.edge_clear(centre[0] + dx, centre[2] + dz, g[0]) >= 1.0:
                    seeds.append((centre[0] + dx, g[0], centre[2] + dz))
    for s in seeds:
        sp = grid.ground(s[0], s[2], s[1], 0.7)
        if sp is None:
            continue
        base = route_dir(ctx, sp[1], toward_poly)
        if base is None:
            continue
        for dyaw in (0, 0.3, -0.3, 0.6, -0.6, 0.8, -0.8):
            r = fit_group(ctx, s, base + dyaw)
            if r is None:
                continue
            score = r[0] - 4.0 * abs(dyaw) - 0.15 * math.dist(s, centre)
            if best is None or score > best[0]:
                best = (score, s, base + dyaw, r[1], sp[1])
    return best


def pick_end_anchors(ctx, key):
    """spec "starts_at_ends": the team starts sit at the two ENDS of a long play rectangle (z max = team 0, z min = team 1), near its centre line"""
    nav, grid = ctx.nav, ctx.grid
    cs = candidates(ctx, 3.0, 1.5)
    zs = [c.pos[2] for c in cs]
    zmax, zmin = max(zs), min(zs)
    b = ctx.bounds
    xc = (b[0] + b[1]) / 2
    span = zmax - zmin
    ends = []
    for sgn, name in ((1, "top"), (-1, "bottom")):
        band = [c for c in cs if (c.pos[2] >= zmax - 0.16 * span if sgn > 0 else c.pos[2] <= zmin + 0.16 * span)]
        band.sort(key=lambda c: abs(c.pos[0] - xc) + 0.25 * abs(c.pos[2] - (zmax if sgn > 0 else zmin)))
        ends.append(band[:60])
    other = {0: ends[1][0], 1: ends[0][0]}
    groups = [[], []]
    for e in (0, 1):
        for c in ends[e][::3]:
            g = best_group(ctx, c.pos, c.poly, other[e].poly, 6.0)
            if g:
                groups[e].append((g[0] - 0.12 * abs(c.pos[0] - xc) - 0.08 * abs(c.pos[2] - (zmax if e == 0 else zmin)), g))
        groups[e].sort(key=lambda t: -t[0])
    if not groups[0] or not groups[1]:
        raise SystemExit(f"{key}: no start group fits at the ends of the play rectangle")
    pick = None
    for sa, ga in groups[0][:10]:                  # best pair whose groups do not see each other (a 120 m straight sight line otherwise)
        for sb, gb in groups[1][:10]:
            if not any(grid.los(a, c) for a in ga[3] for c in gb[3] if math.dist(a, c) < 200):
                if pick is None or sa + sb > pick[0]:
                    pick = (sa + sb, ga, gb)
    if pick is None:
        pick = (0, groups[0][0][1], groups[1][0][1])
        print(f"{key}: warning: the end groups see each other (nav sight line)")
    g0, g1 = pick[1], pick[2]
    pd = dijkstra_pred(nav, g0[4])[0].get(g1[4], float("nan"))
    return g0, g1, "team starts at the two ends of the play rectangle (path %.0f m)" % pd


def pick_region_anchors(ctx, key):
    """spec "start_regions": [[x0, x1, z0, z1] for team 0, [...] for team 1]: each team's start group sits inside its rectangle (compact
    multi-building maps: the teams start on the streets, not inside a shop). The best pair that does not see each other wins."""
    nav, grid = ctx.nav, ctx.grid
    regs = ctx.spec["start_regions"]
    cs = candidates(ctx, 2.0, 1.5)
    rc = [(r[0] + r[1]) / 2 for r in regs], [(r[2] + r[3]) / 2 for r in regs]
    sets = []
    for r, cx, cz in zip(regs, *rc):
        band = [c for c in cs if r[0] <= c.pos[0] <= r[1] and r[2] <= c.pos[2] <= r[3] and L.floor_index(ctx.spec, c.pos) < 0]
        band.sort(key=lambda c: math.hypot(c.pos[0] - cx, c.pos[2] - cz))
        if not band:
            raise SystemExit(f"{key}: no start candidate inside the start region {r}")
        sets.append(band)
    other = {0: sets[1][0], 1: sets[0][0]}
    groups = [[], []]
    for e in (0, 1):
        for c in sets[e][::2][:40]:
            g = best_group(ctx, c.pos, c.poly, other[e].poly, 6.0)
            if g:
                groups[e].append((g[0] - 0.10 * math.hypot(c.pos[0] - rc[0][e], c.pos[2] - rc[1][e]), g))
        groups[e].sort(key=lambda t: -t[0])
    if not groups[0] or not groups[1]:
        raise SystemExit(f"{key}: no start group fits inside the start regions")
    lo, hi = ctx.spec.get("team_path") or ([60.0, 90.0] if L.maxteam(key) <= 3 else [80.0, 110.0])
    import spawn_intro as SI          # the intro camera check (frame, men hidden behind a teammate, ground ahead / behind) and its formation fit

    def refine(g, own, oth):
        """the group re-fitted by spawn_intro (formations, intro camera report without errors) around g's centre -> g' or None"""
        lay_t = {"intro0": own, "intro1": oth, "respawns": []}
        for relax, rad in ((0, 7.0), (1, 7.0)):
            for sc, c, yaw, pts, rep in SI._fit_team(ctx, lay_t, 0, rad, relax)[:1]:
                gp = grid.ground(c[0], c[2], c[1], 1.0)
                if gp:
                    return (sc, c, yaw, [tuple(p["pos"]) for p in pts], gp[1])
        return None

    def mk(g):
        return [{"pos": [round(v, 3) for v in p], "quat": yaw_quat(g[2])} for p in g[3]]
    pairs = []
    for sa, ga in groups[0][:24]:
        for sb, gb in groups[1][:24]:
            if any(grid.los(a, c) for a in ga[3] for c in gb[3] if math.dist(a, c) < 200):
                continue
            pd = dijkstra_pred(nav, ga[4])[0].get(gb[4])
            if pd is None or not lo <= pd <= hi:
                continue
            bal = L.start_balance(ctx, ga[4], gb[4])
            if not RULES["start_balance"][0] <= bal <= RULES["start_balance"][1]:
                continue
            pairs.append((sa + sb - 20 * abs(bal - 0.5), ga, gb, pd))
    pairs.sort(key=lambda t: -t[0])
    cache, pick = {}, None
    for tot, ga, gb, pd in pairs[:40]:
        ra = cache.setdefault(id(ga), None) or refine(ga, mk(ga), mk(gb))
        cache[id(ga)] = ra
        rb = cache.setdefault(id(gb), None) or refine(gb, mk(gb), mk(ga))
        cache[id(gb)] = rb
        if ra is None or rb is None:
            continue
        if any(grid.los(a, c) for a in ra[3] for c in rb[3] if math.dist(a, c) < 200):
            continue
        pd2 = dijkstra_pred(nav, ra[4])[0].get(rb[4])
        if pd2 is None or not lo <= pd2 <= hi:
            continue
        pick = (ra, rb, pd2)
        break
    if pick is None and ctx.spec.get("intro_relax") and pairs:        # spec "intro_relax": a cluttered interior with no room for the intro camera anywhere (Chase: the terminal
        ga, gb, pd = pairs[0][1], pairs[0][2], pairs[0][3]           # table / rail maze): the best pair without the intro-camera refit (the camera report is then warnings to check in game)
        print(f"{key}: intro_relax: no start pair passes the intro camera, using the best unrefined pair")
        pick = ((ga[0], ga[1], ga[2], [tuple(p) for p in ga[3]], ga[4]), (gb[0], gb[1], gb[2], [tuple(p) for p in gb[3]], gb[4]), pd)
    if pick is None:
        raise SystemExit(f"{key}: no pair of start groups in the regions passes (path {lo:.0f}-{hi:.0f} m, no sight line, balance, intro camera)")
    return pick[0], pick[1], "team starts inside the spec start regions, intro-camera checked (path %.0f m)" % pick[2]


def pick_anchors(ctx, lay, key):
    if ctx.spec.get("start_regions"):
        return pick_region_anchors(ctx, key)
    if ctx.spec.get("starts_at_ends"):
        return pick_end_anchors(ctx, key)
    """-> (group0, group1, how); a group = (score, centre, yaw, [4 positions], poly). Keep the current team areas when they pass
    (path range, no sight line between any two spawns of the two groups, a wedge fits); otherwise search pairs like
    nav_plan.seed and keep the best by the same screen plus the group fit."""
    nav, grid = ctx.nav, ctx.grid
    mt = L.maxteam(key)
    spec = ctx.spec
    lo, hi = spec.get("team_path") or ([60.0, 90.0] if mt <= 3 else [80.0, 110.0])
    mid_p = (lo + hi) / 2

    def evaluate(c0, p0, c1, p1, radius):
        d, _ = dijkstra_pred(nav, p0)
        pd = d.get(p1)
        if pd is None or not lo <= pd <= hi:
            return None
        bal = L.start_balance(ctx, p0, p1)
        if not RULES["start_balance"][0] <= bal <= RULES["start_balance"][1]:
            return None
        g0 = best_group(ctx, c0, p0, p1, radius)
        g1 = best_group(ctx, c1, p1, p0, radius)
        if not g0 or not g1:
            return None
        if any(grid.los(a, b) for a in g0[3] for b in g1[3] if math.dist(a, b) < 150):
            return None
        return g0, g1, pd, bal

    cur = None
    if lay and lay.get("intro0") and lay.get("intro1"):
        c0, c1 = L.centre(lay["intro0"]), L.centre(lay["intro1"])
        p0 = ctx.poly_at(c0) if ctx.poly_at(c0) is not None else ctx.poly_at(lay["intro0"][0]["pos"])
        p1 = ctx.poly_at(c1) if ctx.poly_at(c1) is not None else ctx.poly_at(lay["intro1"][0]["pos"])
        if p0 is not None and p1 is not None and p0 in ctx.play and p1 in ctx.play:
            for radius in (8.0, 14.0):
                r = evaluate(tuple(c0), p0, tuple(c1), p1, radius)
                if r:
                    return r[0], r[1], "kept the current team areas (path %.0f m, %.0f%% of the map nearer team 0, group search radius %.0f m)" % (r[2], 100 * r[3], radius)
    cs = candidates(ctx, 4.0, 1.2)
    mid = (sum(c.pos[0] for c in cs) / len(cs), sum(c.pos[2] for c in cs) / len(cs))
    sample = cs[::max(1, len(cs) // 160)]
    pairs = []
    for a in sample:
        d, _ = dijkstra_pred(nav, a.poly)
        for b in sample:
            if b.poly <= a.poly or b.poly not in d:
                continue
            pd = d[b.poly]
            if not lo <= pd <= hi or math.dist(a.pos, b.pos) < 0.6 * pd:
                continue
            span = math.hypot(a.pos[0] - mid[0], a.pos[2] - mid[1]) + math.hypot(b.pos[0] - mid[0], b.pos[2] - mid[1])
            pairs.append((abs(pd - mid_p) * 0.5 - span * 0.5 - math.dist(a.pos, b.pos), a, b, pd))
    pairs.sort(key=lambda t: t[0])
    best, tried, seen = None, 0, []
    for sc, a, b, pd in pairs:
        if any(math.dist(a.pos, q[0]) < 20 and math.dist(b.pos, q[1]) < 20 for q in seen):
            continue
        seen.append((a.pos, b.pos))
        r = evaluate(a.pos, a.poly, b.pos, b.poly, 6.0)
        tried += 1
        if r:
            tot = r[0][0] + r[1][0] + sc * 0.05 - 40 * abs(r[3] - 0.5)
            if best is None or tot > best[0]:
                best = (tot, r)
        if tried >= 30 and best:
            break
        if tried >= 90:
            break
    if best is None:
        raise SystemExit(f"{key}: no pair of team areas passes (path {lo:.0f}-{hi:.0f} m, no sight line, a group fits)")
    r = best[1]
    return r[0], r[1], "searched a new pair of team areas (path %.0f m, %.0f%% of the map nearer team 0)" % (r[2], 100 * r[3])


