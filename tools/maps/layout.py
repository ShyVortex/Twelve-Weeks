def seed_file(key):
    return os.path.join(L.SEEDS, (f"pool-{POOL[key][1]}" if key in POOL else key) + ".json")


def box_pool(ctx, key, g0, g1, resp_pos, tr, da, db, intro_pts, flat_max):
    """box candidates: reachable, off the nav edge, flat ground under the crate (it must not float), away from respawns / starts.
    Per candidate: c.open = traffic of the shortest routes between starts / respawns (0 = nobody walks there), c.cov = cover score,
    c.inside = index of the enclosed space it stands in (-1 outside), c.vant = elevated inside (an upper floor / window spot),
    c.land = nearness to a landmark (0..1), c.edgef = how far from the map centre (0..1)"""
    grid = ctx.grid
    ints = E.interiors(ctx, seed_file(key))
    inside = E.interior_index(ints)
    lms = E.landmarks(ctx, ints, seed_file(key))
    cs = candidates(ctx, 1.5, RULES["box_edge_clear"])
    excl = E.box_exclusions(ctx, seed_file(key))
    cs = [c for c in cs if not any(math.hypot(c.pos[0] - x, c.pos[2] - z) < r for x, z, r in excl)]     # not in boxcars / the cart-ladder-resort route
    cx = sum(c.pos[0] for c in cs) / len(cs)
    cz = sum(c.pos[2] for c in cs) / len(cs)
    rmax = max(math.hypot(c.pos[0] - cx, c.pos[2] - cz) for c in cs) or 1.0
    ylow = {}
    for c in cs:
        k = (int(c.pos[0] // 12), int(c.pos[2] // 12))
        ylow[k] = min(ylow.get(k, 1e9), c.pos[1])
    pool = []
    for c in cs:
        if c.poly not in da or c.poly not in db:
            continue
        c.inside = inside(c.pos)
        # a box 6-10 m from a respawn is accepted inside a building (small spaces cannot keep 10 m from every respawn)
        if resp_pos and min(math.dist(c.pos, q) for q in resp_pos) < (6.0 if c.inside >= 0 else RULES["box_resp_min"]):
            continue
        if min(math.dist(c.pos, q) for q in intro_pts) < 12.0:
            continue
        if E.flat(grid, c.pos) > flat_max:
            continue
        c.da, c.db = da[c.poly], db[c.poly]
        c.open = tr.get(c.poly, 0.0)
        c.cov = E.cover_score(E.cover(grid, c.pos))
        k = (int(c.pos[0] // 12), int(c.pos[2] // 12))
        low = min(ylow.get((k[0] + i, k[1] + j), 1e9) for i in (-1, 0, 1) for j in (-1, 0, 1))
        c.vant = 1.0 if c.inside >= 0 and c.pos[1] - low >= 2.5 else 0.0
        c.floor = L.floor_index(ctx.spec, c.pos)
        dl = min((math.hypot(c.pos[0] - x, c.pos[2] - z) for x, z in lms), default=99.0)
        c.land = max(0.0, 1.0 - dl / 25.0)
        c.edgef = min(1.0, math.hypot(c.pos[0] - cx, c.pos[2] - cz) / rmax)
        pool.append(c)
    return pool


# box scoring: draw players to spots they would skip. Cover is nice-to-have only (0.15), spread / rarity / landmarks lead.
W_RARE, W_LAND, W_EDGE, W_SPREAD, W_COVER, W_VANT = 0.9, 0.7, 0.4, 0.7, 0.15, 0.8


def spread_of(c, chosen):
    return min(1.0, min(math.dist(c.pos, q.pos) for q in chosen) / 40.0) if chosen else 0.5


def bscore(c, chosen):
    """exterior contested box: off the main routes (rarity), at a landmark / the map edge, away from the other boxes"""
    return W_RARE * (1.0 - c.open) + W_LAND * c.land + W_EDGE * c.edgef + W_SPREAD * spread_of(c, chosen) + W_COVER * c.cov


def iscore(c, chosen):
    """interior box: a vantage (upper floor), off the routes, spread, a space of its own (spaces already holding a box lose)"""
    again = sum(1 for q in chosen if getattr(q, "inside", -1) == c.inside)
    return W_VANT * c.vant + 0.5 * W_RARE * (1.0 - c.open) + W_SPREAD * spread_of(c, chosen) + W_COVER * c.cov + 0.3 * c.land - 0.6 * again


def box_spacing(area, n):
    """minimum PATH distance between any two boxes (m). 2013 boxes were spread out; the hand placed pool maps keep 14-22 m (path) between
    a box and its nearest neighbour (median 19-36): max(24, 0.95 * sqrt(area / boxes)), accepted down to 0.8 of it: 20-28 m on the maps here."""
    return max(24.0, 0.95 * math.sqrt(area / max(1, n)))


def gen_boxes(ctx, key, g0, g1, resp, cands, n, fixed=(), S0=None, half=None):
    """n boxes (fewer when the spacing does not leave room: never below RULES[box_min]); `fixed` = candidates that are already placed
    (approved spots), counted in every rule"""
    nav, grid = ctx.nav, ctx.grid
    intro_pts = g0[3] + g1[3]
    da, _ = dijkstra_pred(nav, g0[4])
    db, _ = dijkstra_pred(nav, g1[4])
    rp = [r.pos for r in resp]
    nodes = [g0[4], g1[4]] + [r.poly for r in resp]
    if not resp and cands:                      # boxes first: the route traffic comes from a lattice of pseudo respawns
        nodes += [c.poly for c in cands[::max(1, len(cands) // 24)]]
    tr = traffic(ctx, list(dict.fromkeys(nodes)))
    pool = box_pool(ctx, key, g0, g1, rp, tr, da, db, intro_pts, E.FLAT_MAX)
    ints = E.interiors(ctx, seed_file(key))
    inside_fn = E.interior_index(ints)
    in_area = sum(c["area"] for c in ints if c["area"] >= 80.0)
    area = sum(nav.area[i] for i in ctx.play)
    want_in = 0
    if in_area >= 150 and ints:
        share = float(ctx.spec.get("inside_share", 0.45))      # map spec: Jackson Suburbs: boxes mainly INTO the houses
        want_in = max(1, min(int(round(share * n)), len([c for c in ints if c["area"] >= 80.0]) * 3))
    chosen = list(fixed)
    for fb in (ctx.spec.get("fixed_boxes") or []):       # hand placed spots (F8 marks): floor Y and facing from the mark, counted in every rule
        fx, fy, fz = fb["pos"]
        pos = (fx, fy, fz)
        poly = ctx.poly_at(pos)
        if poly is None or poly not in da or poly not in db:
            print(f"{key}: fixed box at {fx:.1f}, {fz:.1f} is not on reachable ground: skipped")
            continue
        c = Cand(pos, poly)
        c.edge, c.da, c.db = nav.edge_clear(fx, fz, fy), da[poly], db[poly]
        c.open = tr.get(poly, 0.0)
        c.cov = E.cover_score(E.cover(grid, pos))
        c.inside = inside_fn(pos)
        c.vant, c.land, c.edgef = 0.0, 0.0, 0.0
        c.ymark = fy
        c.qmark = fb.get("quat")
        chosen.append(c)
    lo, hi = RULES["box_side_path"]
    trees = {}
    regions = ctx.spec.get("box_regions") or []         # rectangles that must hold a box (Outpost: the west arm, a near-choke point)

    def ptree(c):
        if c.poly not in trees:
            trees[c.poly] = dijkstra_pred(nav, c.poly, 80.0)[0]
        return trees[c.poly]

    S0 = S0 or box_spacing(area, n)

    def sep_ok(c, S):
        """path distance >= S and straight distance >= 0.75 S to every chosen box; with `half`, no half of the map holds more than ceil(n / 2) boxes"""
        if half and sum(1 for q in chosen if half(q.pos) == half(c.pos)) >= (n + 1) // 2:
            return False
        for q in chosen:
            Se = min(S, 9.0) if (c.inside >= 0 and q.inside == c.inside) else S      # two boxes in one building: rooms / floors, 9 m is enough
            if math.dist(c.pos, q.pos) < 0.75 * Se or ptree(q).get(c.poly, 1e9) < Se:
                return False
        return True

    def side_of_box(c):
        return 0 if c.da < c.db else 1

    def n_in():
        return sum(1 for q in chosen if q.inside >= 0)

    spac = [S0, 0.9 * S0, 0.8 * S0] + ([0.72 * S0] if half else [])
    # one side box per team: 12-40 m from its own start, clearly closer to it (fairness)
    for own, other in ((0, 1), (1, 0)):
        if any(side_of_box(q) == own and lo <= (q.da, q.db)[own] <= hi for q in chosen):
            continue
        for S in spac:
            cs = [c for c in pool if lo <= (c.da, c.db)[own] <= hi and (c.da, c.db)[own] < RULES["box_side_ratio"] * (c.da, c.db)[other] and sep_ok(c, S)]
            if cs:
                chosen.append(max(cs, key=lambda c: 0.5 * (1.0 - c.open) + W_COVER * c.cov + 0.3 * c.land - 0.02 * abs((c.da, c.db)[own] - 22.0)))
                break
    for rg in regions:
        if any(rg[0] <= q.pos[0] <= rg[1] and rg[2] <= q.pos[2] <= rg[3] for q in chosen):
            continue
        for S in spac:
            cs = [c for c in pool if rg[0] <= c.pos[0] <= rg[1] and rg[2] <= c.pos[2] <= rg[3] and sep_ok(c, S)]
            if cs:
                chosen.append(max(cs, key=lambda c: iscore(c, chosen) + (0.6 if c.inside >= 0 else 0.0)))
                break
    # per-floor quotas (spec "floors": upper floors / roofs): supply boxes there too, spacing relaxed step by step
    for k, f in enumerate(ctx.spec.get("floors") or []):
        need = int(f.get("boxes", 0))
        for S in spac:
            while sum(1 for q in chosen if q.floor == k) < need:
                cs = [c for c in pool if c.floor == k and sep_ok(c, S)]
                if not cs:
                    break
                chosen.append(max(cs, key=lambda c: iscore(c, chosen) + 0.5 * (1.0 - c.open)))
    # interior boxes (the main space first when none is in yet, then the other spaces; vantage spots first)
    for S in spac:
        while n_in() < want_in and len(chosen) < n:
            cs = [c for c in pool if c.inside >= 0 and sep_ok(c, S)]
            if not any(q.inside == 0 for q in chosen):
                cs = [c for c in cs if c.inside == 0] or cs
            if not cs:
                break
            chosen.append(max(cs, key=lambda c: iscore(c, chosen)))
    # the rest outside: off the routes, landmarks, map edges; both sides get the same number of boxes (+-1)
    for S in spac:
        while len(chosen) < n:
            n0 = sum(1 for q in chosen if side_of_box(q) == 0)
            n1 = len(chosen) - n0
            cs = [c for c in pool if c.inside < 0 and sep_ok(c, S) and min(c.da, c.db) >= 14.0 and abs(c.da - c.db) <= 0.7 * max(c.da, c.db)]
            if not cs:
                break
            chosen.append(max(cs, key=lambda c: bscore(c, chosen) - (0.5 if (side_of_box(c) == 0 and n0 - n1 >= 1) or (side_of_box(c) == 1 and n1 - n0 >= 1) else 0.0)))
    for S in spac:                              # still short (a half of the map needs one more): drop the contested-distance condition, keep spacing / halves / rarity
        while len(chosen) < n:
            cs = [c for c in pool if c.inside < 0 and sep_ok(c, S)]
            if not cs:
                break
            chosen.append(max(cs, key=lambda c: bscore(c, chosen)))
    if len(chosen) < n:
        print(f"{key}: only {len(chosen)} of {n} boxes fit {0.8 * S0:.0f}-{S0:.0f} m path spacing")
    return chosen


def spacing_stats(ctx, boxes):
    """(min, median) of every box's nearest-neighbour PATH distance, and the same straight"""
    nav = ctx.nav
    polys = [ctx.poly_at(b["pos"]) for b in boxes]
    npath, nstr = [], []
    for i, pi in enumerate(polys):
        d = dijkstra_pred(nav, pi, 200.0)[0]
        npath.append(min((d.get(q, 1e9) for j, q in enumerate(polys) if j != i), default=0))
        nstr.append(min((math.dist(boxes[i]["pos"], boxes[j]["pos"]) for j in range(len(boxes)) if j != i), default=0))
    srt = sorted(npath)
    return {"path_min": round(min(npath), 1), "path_median": round(srt[len(srt) // 2], 1), "straight_min": round(min(nstr), 1)}


def movebox(key, num, x, z, pak=False):
    """move box `num` (1-based) to the nearest flat spot (floor rule) within 4 m of (x, z); nothing else changes"""
    lay = L.load_layout(key)
    raw = json.load(open(os.path.join(L.DATA, f"{key}-spawns.json")))
    ctx = Ctx(key, lay)
    grid = ctx.grid
    cur = lay["boxes"][num - 1]
    others = [b for i, b in enumerate(lay["boxes"]) if i != num - 1]
    ref = grid.ground(x, z, cur["pos"][1], 6.0)
    base = (x, ref[0] if ref else cur["pos"][1], z)
    cs = fine_flat(ctx, base, 4.0, [tuple(r["pos"]) for r in lay["respawns"]], [tuple(p["pos"]) for p in lay["intro0"] + lay["intro1"]], others)
    if not cs:
        raise SystemExit(f"{key}: no flat spot within 4 m of {x:.1f}, {z:.1f}")
    c = min(cs, key=lambda c: math.dist(c.pos, base) - 0.5 * c.cov)
    box = {"pos": [round(c.pos[0], 3), round(E.snap_y(grid, c.pos), 3), round(c.pos[2], 3)], "quat": yaw_quat(face_open(ctx, c.pos, None, 2.5))}
    print(f"{key}: B{num} {[round(v, 2) for v in cur['pos']]} -> {box['pos']}")
    raw["boxes"][num - 1] = box
    write_data(key, raw)
    lay2 = {k: v for k, v in raw.items() if not k.startswith("_")}
    snapshot(key, lay2)
    ctx2 = Ctx(key, lay2)
    print(preview(key, lay2, ctx2))
    st = spacing_stats(ctx2, lay2["boxes"])
    print("spacing", st)
    with open(LOGF, "a", encoding="utf-8") as f:
        f.write(f"- {key} (movebox): B{num} -> {box['pos']} (out of the boxcar / cart-ladder-resort area); spacing min {st['path_min']} / median {st['path_median']} m\n")
    if pak:
        pak_build(key)


def respace(key, keep_pts, pak=False, n=9):
    """re-place the boxes of a layout that was played, with the spacing rule; `keep_pts` = [(x, z), ...] requested spots (B7 in the station,
    B9 in the opposite building) that stay. Starts and respawns do not move. Tries n boxes, then n - 1 ... (>= 8 when the map is big enough)."""
    lay = L.load_layout(key)
    raw = json.load(open(os.path.join(L.DATA, f"{key}-spawns.json")))
    ctx = Ctx(key, lay)
    nav, grid = ctx.nav, ctx.grid
    p0, p1 = ctx.poly_at(lay["intro0"][0]["pos"]), ctx.poly_at(lay["intro1"][0]["pos"])
    g0 = (0, L.centre(lay["intro0"]), 0, [tuple(p["pos"]) for p in lay["intro0"]], p0)
    g1 = (0, L.centre(lay["intro1"]), 0, [tuple(p["pos"]) for p in lay["intro1"]], p1)

    class R:
        def __init__(self, pos):
            self.pos = tuple(pos)
            self.poly = ctx.poly_at(pos)
    resp = [R(r["pos"]) for r in lay["respawns"]]
    resp = [r for r in resp if r.poly is not None]
    da, _ = dijkstra_pred(nav, p0)
    db, _ = dijkstra_pred(nav, p1)
    intro = g0[3] + g1[3]
    tr = traffic(ctx, list(dict.fromkeys([p0, p1] + [r.poly for r in resp])))
    pool = box_pool(ctx, key, g0, g1, [r.pos for r in resp], tr, da, db, intro, E.FLAT_MAX)
    fixed = []
    for x, z in keep_pts:
        near = [c for c in pool if math.hypot(c.pos[0] - x, c.pos[2] - z) <= 4.0]
        if not near:
            raise SystemExit(f"{key}: no flat spot within 4 m of the kept box at {x:.0f}, {z:.0f}")
        fixed.append(min(near, key=lambda c: math.hypot(c.pos[0] - x, c.pos[2] - z)))
    half = None
    if len(keep_pts) >= 2:             # the two kept landmarks (station / second building) define the long axis: halves = sides of their bisector
        (ax, az), (bx, bz) = keep_pts[0], keep_pts[1]
        mx, mz, dx, dz = (ax + bx) / 2, (az + bz) / 2, bx - ax, bz - az
        half = lambda pos: 0 if (pos[0] - mx) * dx + (pos[2] - mz) * dz < 0 else 1
    out = None
    for nn in range(n, RULES["box_min"] - 1, -1):
        got = gen_boxes(ctx, key, g0, g1, resp, None, nn, fixed, box_spacing(sum(nav.area[i] for i in ctx.play), n), half)
        if len(got) >= nn:
            out = got
            break
    if out is None:
        out = got
    boxes = [{"pos": [round(c.pos[0], 3), round(E.snap_y(grid, c.pos), 3), round(c.pos[2], 3)], "quat": yaw_quat(face_open(ctx, c.pos, None, 2.5))} for c in out]
    st = spacing_stats(ctx, boxes)
    raw["boxes"] = boxes
    write_data(key, raw)
    lay2 = {k: v for k, v in raw.items() if not k.startswith("_")}
    snapshot(key, lay2)
    ctx2 = Ctx(key, lay2)
    print(preview(key, lay2, ctx2))
    err, warn, m = L.check(key, lay2, ctx2, strict=True)
    hc = [sum(1 for b in boxes if half(b["pos"]) == h) for h in (0, 1)] if half else None
    line = (f"- {key} (respace): {len(boxes)} boxes, halves of the long axis {hc}, nearest-neighbour path spacing min {st['path_min']} / median {st['path_median']} m (straight min {st['straight_min']} m); "
            f"inside boxes {m['inside']['boxes']}; kept {keep_pts}")
    print(line)
    with open(LOGF, "a", encoding="utf-8") as f:
        f.write(line + "\n")
    if pak:
        pak_build(key)


