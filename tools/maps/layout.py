def apply_floor(key, out):
    """put every box / respawn / intro of a generated layout on the BAKED real floor (tools/maps/data/<key>-floor.json, written by
    `layout.py floor`) when a baked spawner lies within 0.5 m; the rest keep the navmesh snap"""
