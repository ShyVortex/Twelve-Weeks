def ensure(key):
    """build hook for a selected SP-section map: generate a missing layout, rebuild a stale pak, validate; never fails the build
    unless T2R_LAYOUT_STRICT=1 (a map without a navmesh seed keeps its seeded placeholder layout)"""
    sp = L.spec_of(key)
    if not sp or key in POOL:
        return
    data = os.path.join(L.DATA, f"{key}-spawns.json")
    nav_ok = os.path.exists(L.nav_file(key))
    try:
        if not os.path.exists(data):
            print(f"layout: {key} has no spawns file")
            if os.path.exists(os.path.join(ROOT, "re", "maps", "seeds", f"{key}.json")):
                import sp_maps
                sp_maps.seed(key)
            else:
                print(f"layout: {key}: no spawner seed either (python tools/maps/sp_maps.py extract {key})")
                return
        lay = json.load(open(data))
        if "LAYOUT-GENERATED" not in lay.get("_note", "") and nav_ok and not sp.get("hand_placed"):
            print(f"layout: {key}: generating (tools/maps/layout.py gen)")
            gen_one(key, pak=True)
        elif not nav_ok:
            print(f"layout: {key}: no navmesh seed - layout not generated / checked (re/maps/seeds/{key}-nav.json)")
            return
        err, warn, m = L.check(key, L.load_layout(key), None, strict=True)
        for e in err:
            print(f"layout: {key}: ERROR {e}")
        if err and os.environ.get("T2R_LAYOUT_STRICT") == "1":
            raise SystemExit(f"layout: {key} fails the layout rules")
    except (OSError, subprocess.CalledProcessError) as e:
        print(f"layout: {key}: skipped ({e})")


def rerespawn(key, boxes_fixed=True):
    """a team start moved (hand placed): keep every respawn that still obeys the rules (>= 12 m from every intro spawn, no sight of a start group),
    re-pick the broken ones with the generator's own scoring (same pool, gaps, floors); boxes and the other team stay.  Updates `_anchors`, writes
    the data file + snapshot."""
    raw = json.load(open(os.path.join(L.DATA, f"{key}-spawns.json")))
    lay = {k: v for k, v in raw.items() if not k.startswith("_")}
    ctx = Ctx(key, lay)
    grid = ctx.grid
    anchors = []
    for t in ("intro0", "intro1"):
        pts = [p["pos"] for p in lay[t]]
        c = L.centre(lay[t])
        q = lay[t][0]["quat"]
        yaw = 2.0 * math.atan2(q[1], q[3])
        gp = grid.ground(c[0], c[2], c[1], 1.5)
        anchors.append((0.0, tuple(c), yaw, [tuple(p) for p in pts], gp[1]))
    g0, g1 = anchors
    raw["_anchors"] = [[round(v, 4) for v in g[1]] + [round(g[2], 5)] for g in anchors]
    intro_pts = g0[3] + g1[3]
    keep, drop = [], []
    for r in lay["respawns"]:
        p = tuple(r["pos"])
        bad = min(math.dist(p, q) for q in intro_pts) < RULES["respawn_intro_min"] or any(
            grid.los(p, q) and math.dist(p, q) < RULES["respawn_los_enemy"] for q in intro_pts + [g0[1], g1[1]])
        (drop if bad else keep).append(p)
    print(f"{key}: {len(keep)} respawns stay, {len(drop)} re-picked: {[tuple(round(v, 1) for v in d) for d in drop]}")
    cands = candidates(ctx, 3.0, 1.5)
    n = len(lay["respawns"])

    class B:
        def __init__(self, p):
            self.pos = tuple(p)
    boxes = [B(b["pos"]) for b in lay["boxes"]]
    resp, cov = gen_respawns(ctx, key, g0, g1, cands, n, n, boxes, keep)
    mid = (sum(c.pos[0] for c in cands) / len(cands), sum(c.pos[2] for c in cands) / len(cands))
    kset = {tuple(k) for k in keep}
    out = []
    old = {tuple(r["pos"]): r for r in lay["respawns"]}
    for r in resp:
        if tuple(r.pos) in kset:
            out.append(old[tuple(r.pos)])
        else:
            out.append({"pos": [round(r.pos[0], 3), round(E.snap_y(grid, r.pos, 0.4), 3), round(r.pos[2], 3)], "quat": yaw_quat(face_open(ctx, r.pos, mid))})
    raw["respawns"] = out
    for d in drop:
        print("  moved", [round(v, 2) for v in d], "->", next((o["pos"] for o in out if tuple(o["pos"]) not in kset and tuple(o["pos"]) not in {tuple(x["pos"]) for x in lay["respawns"]}), None))
    write_data(key, raw)
    lay2 = {k: v for k, v in raw.items() if not k.startswith("_")}
    snapshot(key, lay2)
    err, warn, m = L.check(key, lay2, Ctx(key, lay2), strict=True)
    for e in err:
        print("   ERROR", e)
    for w in warn:
        print("   warn ", w)
    print("coverage %.3f" % cov, "respawns", len(out))
    return err


def gen_one(key, pak=False):
    old = L.load_layout(key) if os.path.exists(os.path.join(L.DATA, f"{key}-spawns.json")) else None
    out, ctx, how = generate(key)
    lay = {k: v for k, v in out.items() if not k.startswith("_")}
    err, warn, m = L.check(key, lay, ctx, strict=True)
    write_data(key, out)
    snapshot(key, lay)
    print(preview(key, lay, ctx))
    if old:
        print(log_change(key, old, lay, how, m))
    for e in err:
        print("   ERROR", e)
    for w in warn:
        print("   warn ", w)
    if pak:
        pak_build(key)
    return err


def main(argv):
    if len(argv) < 2:
        print(__doc__)
        return 1
    cmd, rest = argv[1], argv[2:]
    flags = {a for a in rest if a.startswith("--")}
    rest = [a for a in rest if not a.startswith("--")]
    if cmd == "audit":
        for k in keys_arg(rest):
            report(k)
    elif cmd == "gen":
        bad = 0
        for k in rest:
            if k in POOL:
                print(f"{k}: hand-placed pool map - gen never touches it (use extend)")
                continue
            bad += len(gen_one(k, "--pak" in flags))
        return 1 if bad else 0
    elif cmd == "rerespawn":
        for k in rest:
            rerespawn(k)
    elif cmd == "movebox":
        movebox(rest[0], int(rest[1]), float(rest[2]), float(rest[3]), "--pak" in flags)
    elif cmd == "respace":
        nn = next((int(f.split("=")[1]) for f in flags if f.startswith("--n=")), 9)
        respace(rest[0], [(float(rest[i]), float(rest[i + 1])) for i in range(1, len(rest) - 1, 2)], "--pak" in flags, nn)
    elif cmd == "addbox":
        addbox(rest[0], int(rest[1]), "--pak" in flags)
    elif cmd == "floortest":
        floortest(rest[0], "--off" in flags, "--pak" in flags)
    elif cmd == "floor":
        floor_cmd(rest[0], "--pak" in flags)
    elif cmd == "fix":
        for k in rest:
            fix(k, "--pak" in flags)
    elif cmd == "relocate":
        for k in rest:
            relocate(k, "--apply" in flags)
    elif cmd == "extend":
        for k in rest:
            extend(k, "--apply" in flags)
    elif cmd == "snapshot":
        for k in keys_arg(rest):
            snapshot(k)
            print("snapshot", k)
    elif cmd == "preview":
        for k in keys_arg(rest):
            print(preview(k))
    elif cmd == "validate":
        bad = 0
        for k in keys_arg(rest):
            err, warn, m = report(k)
            bad += len(err)
        return 1 if bad else 0
    elif cmd == "ensure":
        for k in rest:
            ensure(k)
    else:
        print(__doc__)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
