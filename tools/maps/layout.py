def hull_of(pts):
    pts = sorted(set(pts))

    def cr(o, a, b):
        return (a[0] - o[0]) * (b[1] - o[1]) - (a[1] - o[1]) * (b[0] - o[0])
    lo = []
    for p in pts:
        while len(lo) >= 2 and cr(lo[-2], lo[-1], p) <= 0:
            lo.pop()
        lo.append(p)
    up = []
    for p in reversed(pts):
        while len(up) >= 2 and cr(up[-2], up[-1], p) <= 0:
            up.pop()
        up.append(p)
    return lo[:-1] + up[:-1]


def hull_dist(h, p):
    """0 inside the convex hull h, else the distance to it (m)"""
    inside, best = True, 1e9
    for i in range(len(h)):
        a, b = h[i], h[(i + 1) % len(h)]
        if (b[0] - a[0]) * (p[1] - a[1]) - (b[1] - a[1]) * (p[0] - a[0]) < 0:
            inside = False
        dx, dz = b[0] - a[0], b[1] - a[1]
        t = max(0.0, min(1.0, ((p[0] - a[0]) * dx + (p[1] - a[1]) * dz) / (dx * dx + dz * dz or 1.0)))
        best = min(best, math.hypot(p[0] - a[0] - t * dx, p[1] - a[1] - t * dz))
    return 0.0 if inside else best


def play_hull(lay, n_resp):
    """the play area on a hand placed map: hull of its starts, boxes and the first n_resp (hand placed) respawns"""
    pts = [(p["pos"][0], p["pos"][2]) for nm in ("intro0", "intro1", "boxes") for p in lay[nm]] + \
          [(p["pos"][0], p["pos"][2]) for p in lay["respawns"][:n_resp]]
    return hull_of(pts)


HAND_NEAR = 16.0     # ... and within this of a hand placed start / box / respawn (m)
HULL_SLACK = 2.0     # an added respawn may lie this far outside the hand placed play area (m)


def relocate(key, apply=False):
    """added respawns (those after POOL_HAND_RESP[key]) that lie outside the hand placed play area (a Resort respawn was out of bounds in a leftover
    SP section of the level) get a new spot INSIDE the hull (coverage / sides / openness as in extend), moved in the pak (levels.move: position only)"""
    n0 = POOL_HAND_RESP[key]
    lay = L.load_layout(key)
    ctx = Ctx(key, lay)
    h = play_hull(lay, n0)
    bad = [i for i in range(n0, len(lay["respawns"])) if hull_dist(h, (lay["respawns"][i]["pos"][0], lay["respawns"][i]["pos"][2])) > HULL_SLACK]
    if not bad:
        print(f"{key}: every added respawn is inside the play area")
        return []
    nav, grid = ctx.nav, ctx.grid
    g0c, g1c = L.centre(lay["intro0"]), L.centre(lay["intro1"])
    p0, p1 = ctx.poly_at(lay["intro0"][0]["pos"]), ctx.poly_at(lay["intro1"][0]["pos"])
    da, _ = dijkstra_pred(nav, p0)
    db, _ = dijkstra_pred(nav, p1)
    intro = lay["intro0"] + lay["intro1"]
    have = [r for i, r in enumerate(lay["respawns"]) if i not in bad]
    total = sum(nav.area[i] for i in ctx.play)
    reach = {}

    def ball(c):
        if c.poly not in reach:
            d, _ = dijkstra_pred(nav, c.poly, RULES["respawn_cover_r"] + 1)
            reach[c.poly] = [u for u, v in d.items() if v <= RULES["respawn_cover_r"] and u in ctx.play]
        return reach[c.poly]
    covered = set()
    for r in have:
        i = ctx.poly_at(r["pos"])
        if i is not None:
            d, _ = dijkstra_pred(nav, i, RULES["respawn_cover_r"] + 1)
            covered.update(u for u, v in d.items() if v <= RULES["respawn_cover_r"] and u in ctx.play)
    handpts = [tuple(p['pos']) for nm in ('intro0', 'intro1', 'boxes') for p in lay[nm]] + [tuple(p['pos']) for p in lay['respawns'][:n0]]
    raw_c = []
    for c in candidates(ctx, 2.0, 1.2):
        if c.poly not in da or c.poly not in db or hull_dist(h, (c.pos[0], c.pos[2])) > 0.0:
            continue
        if min(math.dist(c.pos, q) for q in handpts) > HAND_NEAR:         # near ground where things were hand placed (not a leftover SP corner inside the hull)
            continue
        c.side = side_of(c, da, db)
        c.open = openness(ctx, c.pos)
        c.cov = E.cover_score(E.cover(grid, c.pos))
        c.seen = [grid.los(c.pos, g0c) and math.dist(c.pos, g0c) < 45, grid.los(c.pos, g1c) and math.dist(c.pos, g1c) < 45]
        raw_c.append(c)
    sides = [0, 0, 0]
    for r in have:
        i = ctx.poly_at(r["pos"])
        if i is not None:
            sides[0 if da.get(i, 1e9) + 12 < db.get(i, 1e9) else 1 if db.get(i, 1e9) + 12 < da.get(i, 1e9) else 2] += 1
    mid = (sum(p["pos"][0] for p in have) / len(have), sum(p["pos"][2] for p in have) / len(have))
    chosen = []
    for gap, bx, omin, inro in ((10.0, 8.0, 0.3, 14.0), (8.0, 6.0, 0.2, 12.0), (7.0, 5.0, 0.1, 10.0)):
        pool = [c for c in raw_c if c.open >= omin and min(L.pdist({"pos": c.pos}, q) for q in intro) >= inro
                and min(L.pdist({"pos": c.pos}, q) for q in have) >= gap and min((L.pdist({"pos": c.pos}, q) for q in lay["boxes"]), default=99) >= bx]
        while len(chosen) < len(bad):
            best, bs = None, -1e9
            for c in pool:
                if any(math.dist(c.pos, q.pos) < gap for q in chosen):
                    continue
                gain = sum(nav.area[u] for u in ball(c) if u not in covered) / total
                weak = (sides[1] - sides[0]) if c.side == 0 else (sides[0] - sides[1]) if c.side == 1 else -1
                sc = 6.0 * gain + 0.35 * weak + 0.3 * c.open + 0.1 * c.cov - 0.3 * sum(c.seen)
                if sc > bs:
                    best, bs = c, sc
            if best is None:
                break
            chosen.append(best)
            covered.update(ball(best))
            sides[best.side] += 1
        if len(chosen) >= len(bad):
            break
    if len(chosen) < len(bad):
        print(f"{key}: only {len(chosen)} in-bounds spots for {len(bad)} respawns")
    msgs = []
    for i, c in zip(bad, chosen):
        old = lay["respawns"][i]["pos"]
        new = [round(c.pos[0], 3), round(E.snap_y(grid, c.pos, 0.4), 3), round(c.pos[2], 3)]
        q = yaw_quat(face_open(ctx, c.pos, mid))
        msgs.append(f"R{i + 1}: ({old[0]:.0f}, {old[2]:.0f}) was {hull_dist(h, (old[0], old[2])):.1f} m outside the hand placed play area -> ({new[0]:.0f}, {new[2]:.0f})")
        print("  " + msgs[-1])
        if apply:
            sys.path.insert(0, L.SPAWNS)
            import levels
            levels.view = lambda m: None          # (levels.move writes the A / B spawnview of the map: not wanted here)
            levels.move(key, f"to1-spawn-point-{i + 1}", tuple(new), tuple(q))
    if apply and msgs:
        subprocess.run(["pwsh", "-NoProfile", "-File", os.path.join(L.SPAWNS, "dump_json.ps1"), "-Pak", os.path.abspath(os.path.join(LEVELS, f"to1-pvp-{key}-ingame.pak")),
                        "-Out", os.path.join(L.SPAWNS, f"{key}.json")], check=True)
        with open(LOGF, "a", encoding="utf-8") as f:
            for m in msgs:
                f.write(f"- {key} (out of bounds fix): {m}\n")
    return msgs


def extend(key, apply=False):
    """pool map: respawns to ADD (nothing moves). Rule: at least 2 * max_team + 4, and 28 m coverage >= 88 %."""
    lay = L.load_layout(key)
    ctx = Ctx(key, lay)
    mt = L.maxteam(key)
    need = max(0, 2 * mt + 4 - len(lay["respawns"]), EXTRA_RESP.get(key, 0))
    m0 = L.measure(key, lay, ctx)
    if m0.get("resp_cover", 1) < RULES["respawn_cover_min"] and need == 0:
        need = 2
    if need == 0 or len(lay["respawns"]) >= 16:
        print(f"{key}: {len(lay['respawns'])} respawns, coverage {m0.get('resp_cover')}: nothing to add")
        return []
    nav, grid = ctx.nav, ctx.grid
    g0c, g1c = L.centre(lay["intro0"]), L.centre(lay["intro1"])
    p0, p1 = ctx.poly_at(lay["intro0"][0]["pos"]), ctx.poly_at(lay["intro1"][0]["pos"])
    da, _ = dijkstra_pred(nav, p0)
    db, _ = dijkstra_pred(nav, p1)
    intro = lay["intro0"] + lay["intro1"]
    cands = candidates(ctx, 3.0, 1.5)
    have = lay["respawns"]
    total = sum(nav.area[i] for i in ctx.play)
    reach = {}

    def ball(c):
        if c.poly not in reach:
            d, _ = dijkstra_pred(nav, c.poly, RULES["respawn_cover_r"] + 1)
            reach[c.poly] = [u for u, v in d.items() if v <= RULES["respawn_cover_r"] and u in ctx.play]
        return reach[c.poly]

    covered = set()
    for r in have:
        i = ctx.poly_at(r["pos"])
        if i is not None:
            d, _ = dijkstra_pred(nav, i, RULES["respawn_cover_r"] + 1)
            covered.update(u for u, v in d.items() if v <= RULES["respawn_cover_r"] and u in ctx.play)
    boxes = lay["boxes"]
    hullp = play_hull(lay, POOL_HAND_RESP.get(key, len(lay["respawns"])))
    handp = [tuple(p['pos']) for nm in ('intro0', 'intro1', 'boxes') for p in lay[nm]] + [tuple(p['pos']) for p in lay['respawns'][:POOL_HAND_RESP.get(key, len(lay['respawns']))]]
    pool = []
    for c in cands:
        if c.poly not in da or c.poly not in db:
            continue
        if min(L.pdist({"pos": c.pos}, q) for q in intro) < 14.0 or min(L.pdist({"pos": c.pos}, q) for q in have) < 10.0:
            continue
        if min((L.pdist({"pos": c.pos}, q) for q in boxes), default=99) < 8.0:
            continue
        if hull_dist(hullp, (c.pos[0], c.pos[2])) > 0.0 or min(math.dist(c.pos, q) for q in handp) > HAND_NEAR:   # only inside the hand placed play area
            continue
        c.side = side_of(c, da, db)
        c.open = openness(ctx, c.pos)
        c.cov = E.cover_score(E.cover(grid, c.pos))
        c.da, c.db = da[c.poly], db[c.poly]
        c.seen = [grid.los(c.pos, g0c) and math.dist(c.pos, g0c) < 45, grid.los(c.pos, g1c) and math.dist(c.pos, g1c) < 45]
        if c.open < 0.3:
            continue
        pool.append(c)
    sides = [0, 0, 0]
    for r in have:
        i = ctx.poly_at(r["pos"])
        if i is not None:
            sides[0 if da.get(i, 1e9) + 12 < db.get(i, 1e9) else 1 if db.get(i, 1e9) + 12 < da.get(i, 1e9) else 2] += 1
    chosen = []
    mid = (sum(c.pos[0] for c in cands) / len(cands), sum(c.pos[2] for c in cands) / len(cands))
    while len(chosen) < need:
        best, bs = None, -1e9
        for c in pool:
            if any(math.dist(c.pos, q.pos) < 10.0 for q in chosen):
                continue
            gain = sum(nav.area[u] for u in ball(c) if u not in covered) / total
            weak = (sides[1] - sides[0]) if c.side == 0 else (sides[0] - sides[1]) if c.side == 1 else -1
            s = 6.0 * gain + 0.35 * weak + 0.3 * c.open + 0.3 * c.cov - 0.3 * sum(c.seen)
            if s > bs:
                best, bs = c, s
        if best is None:
            break
        chosen.append(best)
        covered.update(ball(best))
        sides[best.side] += 1
    out = []
    n = len(have)
    for c in chosen:
        n += 1
        out.append({"src": "to1-spawn-point-1", "name": f"to1-spawn-point-{n}", "pos": [round(c.pos[0], 3), round(E.snap_y(grid, c.pos, 0.4), 3), round(c.pos[2], 3)],
                    "quat": yaw_quat(face_open(ctx, c.pos, mid))})
    js = os.path.join(L.SPAWNS, f"{key}-add.json")
    print(f"{key}: +{len(out)} respawns (R{len(have) + 1}..R{n}); coverage {m0.get('resp_cover')} -> {sum(nav.area[u] for u in covered) / total:.3f}; "
          f"sides {sides}")
    if apply:
        json.dump(out, open(js, "w"))
        pak = os.path.join(LEVELS, f"to1-pvp-{key}-ingame.pak")
        subprocess.run(["pwsh", "-NoProfile", "-File", os.path.join(L.SPAWNS, "add_spawners.ps1"), "-Pak", os.path.abspath(pak),
                        "-Json", os.path.abspath(js)], check=True)
        subprocess.run(["pwsh", "-NoProfile", "-File", os.path.join(L.SPAWNS, "dump_json.ps1"), "-Pak", os.path.abspath(pak),
                        "-Out", os.path.join(L.SPAWNS, f"{key}.json")], check=True)
        with open(LOGF, "a", encoding="utf-8") as f:
            f.write(f"- {key}: pool map (hand placed), nothing moved; ADDED respawns R{len(have) + 1}..R{n} "
                    f"(daemon RESPAWNS {len(have)} -> {n}); coverage {m0.get('resp_cover')} -> {sum(nav.area[u] for u in covered) / total:.3f}\n")
    return out


