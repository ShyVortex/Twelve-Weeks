def fix(key, pak=False):
    """repair a layout that was already played, keeping every placement that is right: boxes whose crate would float (uneven ground)
    move to the best flat spot within 8 m (cover / traffic), the box nearest the main interior moves inside it when there is none,
    every box is snapped to the floor, respawns above the snapped floor are lowered. Starts and respawn positions never move."""
    lay = L.load_layout(key)
    raw = json.load(open(os.path.join(L.DATA, f"{key}-spawns.json")))
    ctx = Ctx(key, lay)
    grid, nav = ctx.grid, ctx.nav
    p0, p1 = ctx.poly_at(lay["intro0"][0]["pos"]), ctx.poly_at(lay["intro1"][0]["pos"])
    da, _ = dijkstra_pred(nav, p0)
    db, _ = dijkstra_pred(nav, p1)
    intro = [tuple(p["pos"]) for p in lay["intro0"] + lay["intro1"]]
    resp = [tuple(p["pos"]) for p in lay["respawns"]]
    nodes = [p0, p1] + [ctx.poly_at(r) for r in resp if ctx.poly_at(r) is not None]
    tr = traffic(ctx, list(dict.fromkeys(nodes)))
    pool = box_pool(ctx, key, None, None, resp, tr, da, db, intro, E.FLAT_MAX)
    boxes = [dict(b, pos=list(b["pos"])) for b in lay["boxes"]]
    log = []

    def free(c, skip):
        return all(math.dist(c.pos, b["pos"]) >= 11.0 for i, b in enumerate(boxes) if i != skip)

    ints = E.interiors(ctx, seed_file(key))
    main = ints[0] if ints and ints[0]["area"] >= 150 else None
    if main and not any(E.in_interior(main, b["pos"], 1.5) for b in boxes):
        k = min(range(len(boxes)), key=lambda i: math.hypot(boxes[i]["pos"][0] - main["centre"][0], boxes[i]["pos"][2] - main["centre"][2]))
        cs = [c for c in pool if E.in_interior(main, c.pos, 1.5) and free(c, k)]
        if cs:
            c = max(cs, key=lambda c: 0.8 * c.open + 0.8 * c.cov)
            log.append(f"B{k + 1} moved into the main interior (%.0f m2 at %.0f, %.0f): %s -> %s" % (
                main["area"], main["centre"][0], main["centre"][2], [round(v) for v in boxes[k]["pos"]], [round(v) for v in c.pos]))
            boxes[k] = {"pos": list(c.pos), "quat": yaw_quat(face_open(ctx, c.pos, None, 2.5))}
        else:
            log.append("NO flat candidate inside the main interior")
    for k, b in enumerate(boxes):
        if E.flat(grid, b["pos"]) > E.FLAT_MAX:
            moved = False
            for rad in (2.5, 4.0, 6.0):
                near = [c for c in pool if math.dist(c.pos, b["pos"]) <= rad and free(c, k)] + fine_flat(ctx, b["pos"], rad, resp, intro, [bb for i, bb in enumerate(boxes) if i != k])
                if near:
                    c = min(near, key=lambda c: math.dist(c.pos, b["pos"]) - 0.5 * c.cov)
                    log.append(f"B{k + 1} uneven ground ({E.flat(grid, b['pos']):.2f} m under the crate): moved {math.dist(c.pos, b['pos']):.1f} m to flat ground")
                    boxes[k] = {"pos": list(c.pos), "quat": yaw_quat(face_open(ctx, c.pos, None, 2.5))}
                    moved = True
                    break
            if not moved:
                log.append(f"B{k + 1} uneven ground ({E.flat(grid, b['pos']):.2f} m) and no flat spot within 6 m: kept, snapped to its lowest point")
    for k, b in enumerate(boxes):
        y = E.snap_y(grid, b["pos"])
        if abs(y - b["pos"][1]) > 0.005:
            log.append(f"B{k + 1} Y {b['pos'][1]:.3f} -> {y:.3f}")
        b["pos"] = [round(b["pos"][0], 3), round(y, 3), round(b["pos"][2], 3)]
    out = dict(raw)
    out["boxes"] = boxes
    rs = []
    for k, r in enumerate(lay["respawns"]):
        y = E.snap_y(grid, r["pos"], 0.4)
        if r["pos"][1] - y > 0.15:
            log.append(f"R{k + 1} Y {r['pos'][1]:.3f} -> {y:.3f}")
            r = dict(r, pos=[r["pos"][0], round(y, 3), r["pos"][2]])
        rs.append(r)
    out["respawns"] = rs
    apply_floor(key, out)
    write_data(key, out)
    lay2 = {k2: v for k2, v in out.items() if not k2.startswith("_")}
    snapshot(key, lay2)
    print(preview(key, lay2, Ctx(key, lay2)))
    for l in log:
        print("  ", l)
    with open(LOGF, "a", encoding="utf-8") as f:
        for l in log:
            f.write(f"- {key} (fix): {l}\n")
    if pak:
        pak_build(key)
    return log


