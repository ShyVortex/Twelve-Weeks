def traffic(ctx, nodes):
    """how many shortest paths between the given polys cross each poly (fraction of the maximum)"""
    nav = ctx.nav
    cnt = {}
    trees = {}
    for s in nodes:
        trees[s] = dijkstra_pred(nav, s)
    for s in nodes:
        d, pred = trees[s]
        for t in nodes:
            if t == s or t not in d:
                continue
            u = t
            while u != s and u in pred:
                cnt[u] = cnt.get(u, 0) + 1
                u = pred[u]
    top = max(cnt.values(), default=1)
    return {k: v / top for k, v in cnt.items()}


def side_of(c, da, db):
    a, b = da.get(c.poly, 1e9), db.get(c.poly, 1e9)
    return 0 if a + 12 < b else 1 if b + 12 < a else 2


def gen_respawns(ctx, key, g0, g1, cands, n_min, n_max, boxes=(), keep=()):
    """respawn ring by greedy coverage: each pick maximises the newly covered walkable area within RULES[respawn_cover_r] (path m),
    plus spread, openness (no corner / dead end), minus sight from the team start groups. Stages relax gap / openness when the
    pool runs dry before n_min."""
    best = None
    for gap, omin in ((10.0, 0.25), (8.5, 0.18), (7.0, 0.10)):
        r = _gen_respawns(ctx, key, g0, g1, cands, n_min, n_max, gap, omin, boxes, keep)
        if best is None or len(r[0]) > len(best[0]):
            best = r
        if len(r[0]) >= n_min:
            break
    return best


def _gen_respawns(ctx, key, g0, g1, cands, n_min, n_max, gap, omin, boxes=(), keep=()):
    nav, grid = ctx.nav, ctx.grid
    intro_pts = g0[3] + g1[3]
    da, _ = dijkstra_pred(nav, g0[4])
    db, _ = dijkstra_pred(nav, g1[4])
    total = sum(nav.area[i] for i in ctx.play)
    ints = E.interiors(ctx, seed_file(key))
    inside = E.interior_index(ints)
    in_area = sum(c["area"] for c in ints if c["area"] >= 80.0)
    edge_band = None
    if ctx.spec.get("respawn_edges") and ctx.bounds:
        edge_band = ((ctx.bounds[0] + ctx.bounds[1]) / 2, 0.12 * (ctx.bounds[1] - ctx.bounds[0]) / 2)
    pool = []
    for c in cands:
        if min(math.dist(c.pos, q) for q in intro_pts) < RULES["respawn_intro_min"]:
            continue
        if c.edge < 1.5 or c.poly not in da or c.poly not in db:
            continue
        if boxes and min(math.dist(c.pos, b.pos) for b in boxes) < 8.0:          # the boxes are placed first (they need the room on small maps)
            continue
        if edge_band and abs(c.pos[0] - edge_band[0]) < edge_band[1]:             # spec "respawn_edges": only along the left / right edges of the rectangle
            continue
        c.side = side_of(c, da, db)
        c.da, c.db = da[c.poly], db[c.poly]
        c.open = openness(ctx, c.pos)
        c.cov = E.cover_score(E.cover(grid, c.pos))
        c.inside = inside(c.pos)
        c.seen = [grid.los(c.pos, g0[1]) and math.dist(c.pos, g0[1]) < RULES["respawn_los_enemy"],
                  grid.los(c.pos, g1[1]) and math.dist(c.pos, g1[1]) < RULES["respawn_los_enemy"]]
        c.floor = L.floor_index(ctx.spec, c.pos)
        if ctx.spec.get("respawn_hide") and (any(c.seen) or any(grid.los(c.pos, q) and math.dist(c.pos, q) < RULES["respawn_los_enemy"] for q in intro_pts)):        # map spec "respawn_hide": no respawn in sight of a start group (hard rule)
            continue
        if c.open < (omin * 0.4 if c.floor >= 0 else omin):          # upper floors (rooms, corridors) are never as open as a street
            continue
        pool.append(c)
    reach = {}
    fl_need = [int(f.get("respawns", 0)) for f in (ctx.spec.get("floors") or [])]      # spec "floors": per-floor respawn quotas

    def ball(c):
        if c.poly not in reach:
            d, _ = dijkstra_pred(nav, c.poly, RULES["respawn_cover_r"] + 1)
            reach[c.poly] = [u for u, v in d.items() if v <= RULES["respawn_cover_r"] and u in ctx.play]
        return reach[c.poly]

    covered = set()
    chosen = []
    cnt = [0, 0, 0]
    for kp in keep:                         # respawns that stay (a team start moved: only the broken ones are re-picked)
        c = Cand(tuple(kp), ctx.poly_at(tuple(kp)))
        c.side = side_of(c, da, db)
        c.da, c.db = da.get(c.poly, 1e9), db.get(c.poly, 1e9)
        c.open = openness(ctx, c.pos)
        c.cov = E.cover_score(E.cover(grid, c.pos))
        c.inside = inside(c.pos)
        c.floor = L.floor_index(ctx.spec, c.pos)
        c.seen = [False, False]
        chosen.append(c)
        covered.update(ball(c))
        cnt[c.side] += 1
    while len(chosen) < n_max:
        best, bs, bg = None, -1e9, 0.0
        mg = 0.0
        for c in pool:
            if any(math.dist(c.pos, q.pos) < gap for q in chosen):
                continue
            imb = 0
            if c.side < 2:
                imb = cnt[c.side] - cnt[1 - c.side]
                if imb >= 3:
                    continue
            elif cnt[2] >= max(2, n_max // 4):
                continue
            gain = sum(nav.area[u] for u in ball(c) if u not in covered) / total
            near = min([c.da, c.db] + [hd_path(ctx, q, c) for q in chosen[-8:]])
            spread = min(1.0, near / 25.0)
            mg = max(mg, gain)
            nin = sum(1 for q in chosen if q.inside >= 0)
            rb = 0.0
            for rg in (ctx.spec.get("respawn_regions") or []):      # a respawn inside each of these rectangles (Outpost: the west arm)
                if rg[0] <= c.pos[0] <= rg[1] and rg[2] <= c.pos[2] <= rg[3] and not any(rg[0] <= q.pos[0] <= rg[1] and rg[2] <= q.pos[2] <= rg[3] for q in chosen):
                    rb = 1.5
            if c.floor >= 0 and sum(1 for q in chosen if q.floor == c.floor) < fl_need[c.floor]:
                rb += 2.5                       # this floor still lacks its quota of respawns: it wins over the street
            lr = 0.0
            if edge_band:                       # left and right edge get the same number (+-1)
                nl = sum(1 for q in chosen if q.pos[0] < edge_band[0])
                lr = 0.6 if ((c.pos[0] < edge_band[0] and nl - (len(chosen) - nl) >= 1) or (c.pos[0] >= edge_band[0] and (len(chosen) - nl) - nl >= 1)) else 0.0
            want_in = in_area >= 150 and c.inside >= 0 and nin < 0.4 * (len(chosen) + 1)    # inside / outside balance (40-50 % inside)
            sc = 16.0 * gain + 0.6 * spread + 0.4 * c.open + 0.1 * c.cov + (0.5 if want_in else 0.0) - 0.3 * sum(c.seen) - 0.2 * max(0, imb) - lr + rb
            if sc > bs:
                best, bs, bg = c, sc, gain
        if best is None:
            break
        cov_now = sum(nav.area[u] for u in covered) / total
        if len(chosen) >= n_min and (cov_now >= 0.93 or mg < 0.01):
            break
        chosen.append(best)
        covered.update(ball(best))
        cnt[best.side] += 1
    return chosen, sum(nav.area[u] for u in covered) / total


_pd_cache = {}


def hd_path(ctx, a, b):
    key = (id(ctx), a.poly)
    if key not in _pd_cache:
        _pd_cache[key] = dijkstra_pred(ctx.nav, a.poly, 60)[0]
    return _pd_cache[key].get(b.poly, 1e9)


def face_open(ctx, pos, toward=None, lo=5.0):
    """yaw with the longest walkable run (cap 10 m), leaning to `toward` (x, z) when given"""
    best, by = None, -1e9
    for yaw in DIRS16:
        run = ctx.grid.run(pos, yaw, 10.0)
        s = min(run, 10.0)
        if toward:
            tw = math.atan2(toward[0] - pos[0], toward[1] - pos[2])
            s += 3.0 * math.cos(L.ang_diff(yaw, tw))
        if run < lo:
            s -= 6
        if s > by:
            best, by = yaw, s
    return best


