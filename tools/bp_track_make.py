"""bp_track_make.py LOG... -> tools/ext/bp_track.h from 'bptrack: clip C idx I rel X Y Z' lines of a recorder run (t2r-bp-record.txt next to the exe, open + close the TAB bag on your own body).
Several runs are averaged per (clip, idx)."""
import re, sys, collections
acc = collections.defaultdict(list)
for fn in sys.argv[1:]:
    for ln in open(fn, errors="replace"):
        m = re.search(r"bptrack: clip (\d) idx (\d+) rel (\S+) (\S+) (\S+)", ln)
        if m:
            acc[(int(m[1]), int(m[2]))].append([float(m[3]), float(m[4]), float(m[5])])
out = ["// bp_track.h - recorded own-body TAB bag prop track (generated by tools/bp_track_make.py)",
       "static const struct { uint8_t c; uint16_t i; float v[3]; } BPT_H[] = {"]
for (c, i), v in sorted(acc.items()):
    a = [sum(x[k] for x in v) / len(v) for k in range(3)]
    out.append("    {%d, %d, {%.5ff, %.5ff, %.5ff}}," % (c, i, *a))
out += ["    {0, 0, {0, 0, 0}}};", "#define BPT_H_N %d" % len(acc), ""]
open(__file__.replace("bp_track_make.py", "ext/bp_track.h"), "w", newline="\n").write("\n".join(out))
print(len(acc), "samples")
