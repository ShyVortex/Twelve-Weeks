"""sp_lighting (tools/maps/sp_lighting.py, sp_maps.json "sp_lighting"): the gated render-settings regions the SP task state selects get
their gating tags cut out of the staged -ingame pak by a pure byte patch.  Needs the cached stock paks (git-ignored level-edit cache of the
main checkout); skipped without them.  Also checks the generated ext header is current."""
import os
import sys
import tempfile
import sys as _t2s, os as _t2o; _t2s.path.append(_t2o.path.normpath(_t2o.path.join(_t2o.path.dirname(_t2o.path.abspath(__file__)), ".."))); import t2rtmp  # noqa: E402,F401

HERE = os.path.dirname(os.path.abspath(__file__))
TOOLS = os.path.dirname(HERE)
sys.path.insert(0, os.path.join(TOOLS, "maps"))
sys.path.insert(0, os.path.join(TOOLS, "part1"))
import sp_lighting as L  # noqa: E402
import p1_rsenv as rs  # noqa: E402

m = L.spec_of("jackson-market")
assert m["sp_lighting"]["task"]["subnode"] == "pat-supermarket-entrance-done"
want = open(L.HEADER, encoding="utf-8").read()   # committed header (regenerated by the build)
if not os.path.exists(L.src_pak("pat-const-render") or ""):
    print("skip: no cached pat-const-render-ingame.pak")
    sys.exit(0)
sel, rows = L.plan(m)
assert len(rows) == 26, len(rows)                 # the 26 task-gated regions near the store
on = sorted(n for names in sel.values() for n in names)
# SP-exact: exact region volumes need no exclusions (T2R_SPL_GATES=old restores the old exclude list: only side-opti-1 then)
assert on == ["rr-pat-cloud-shadows-on-1", "rr-pat-exp-1-7", "rr-pat-supermarket-side-blds-1", "rr-pat-supermarket-side-blds-3", "rr-pat-supermarket-side-opti-1"], on
os.environ["T2R_SPL_GATES"] = "old"
assert sorted(n for names in L.plan(m)[0].values() for n in names) == ["rr-pat-supermarket-side-opti-1"]
del os.environ["T2R_SPL_GATES"]
assert L.dropped(m) == {}                          # SP-exact: no region lost its render-settings symbol (T2R_SPL_DROP=old restores the 11 cuts)
os.environ["T2R_SPL_DROP"] = "old"
assert len(L.dropped(m)) == 11
del os.environ["T2R_SPL_DROP"]
with tempfile.TemporaryDirectory() as td:
    files = L.build(m, out_dir=td, log=lambda *_: None)
    assert [os.path.basename(f) for f in files] == ["pat-const-render-ingame.pak"]
    old = open(L.src_pak("pat-const-render"), "rb").read()
    new = open(files[0], "rb").read()
    assert len(old) == len(new)
    assert not L.verify(old, new, set(on))
    got = {r["name"]: L.gate_of(r) for regs, _ in rs.read_pak_regions(new) for r in regs}
    assert all(got[n] is None for n in on)
    assert got["rr-pat-supermarket-app-opti-1"] is not None and got["rr-pat-forest-blizzard-opti-b-main-1"] is not None   # other states stay gated
    again, done = L.strip_gating(new, set(on))                                  # idempotent
    assert again == new and not done
vols = L.interior_volumes(m)                       # exact convex volumes of main-bld-low-1 (6) + side-blds-1 (2) + hunting-1 (1)
assert len(vols) == 9 and all(len(v) == 6 for v in vols)
def _in(p):
    return any(all(f[0] * p[0] + f[1] * p[1] + f[2] * p[2] <= f[3] for f in v) for v in vols)
assert _in((-520.0, 19.0, 262.0)) and _in((-500.0, 19.5, 290.0)) and not _in((-480.0, 19.0, 262.0))    # store hall, post office, lot
assert "pat-jackson-supermarket" in want
assert "ev_in" not in m["sp_lighting"] and len(L.hold_symbols(m)) >= 3
print("ok")
