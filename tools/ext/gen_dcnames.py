#!/usr/bin/env python3
"""Generate tools/ext/dcnames.h: every engine native / script function the ext calls by a literal name.

  python tools/ext/gen_dcnames.py            # rewrite dcnames.h
  python tools/ext/gen_dcnames.py --check    # exit 1 when dcnames.h is out of date (tools/tests/test_dcnames.py)

Sources scanned: tools/ext/*.c|*.h (not dcnames.h itself) for  dc_call(fnv64("x") / dc_callable(fnv64("x") / fk_q("x" / dc_call(0x...ULL /* x */.
t2r-ext.c's dc_audit_tick() looks every name up in the engine's record table (the same lookup dc_call uses) once a match is running and logs the ones
that are not registered, so a name that does not exist (audit: get-locator, camera-position, player-sprinting? ... answered ~0 for months) shows
up in the first log instead of staying silent. LATE names register only with a level's HUD / script modules and are skipped.
Probe tables (name arrays that are tried on purpose until one answers) are not literal calls and are not listed.
"""
import glob
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "dcnames.h")
LATE = ("hud2-", "gui2-")      # registered when a HUD / menu page exists


def fnv(s):
    h = 0xCBF29CE484222325
    for c in s.encode():
        h = ((h ^ c) * 0x100000001B3) & 0xFFFFFFFFFFFFFFFF
    return h


def collect():
    names = {}
    pats = [re.compile(r'\b(?:dc_call|dc_callable)\(\s*fnv64\("([^"]+)"\)'),
            re.compile(r'\bfk_q\(\s*"([^"]+)"'),
            re.compile(r'\b(?:dc_call|dc_callable)\(\s*0x([0-9a-fA-F]{12,16})ULL\s*/\*\s*([^*]+?)\s*\*/')]
    for f in sorted(glob.glob(os.path.join(HERE, "*.[ch]"))):
        if os.path.basename(f) == "dcnames.h":
            continue
        t = open(f, encoding="latin-1").read()
        for p in pats[:2]:
            for m in p.finditer(t):
                names[m.group(1)] = fnv(m.group(1))
        for m in pats[2].finditer(t):
            n = m.group(2)
            if re.fullmatch(r"[A-Za-z0-9_?!*/<>.+-]+", n) and fnv(n) == int(m.group(1), 16):
                names[n] = fnv(n)
    return names


def render(names):
    rows = sorted(names.items())
    out = ["// GENERATED by tools/ext/gen_dcnames.py - do not edit. Every literal native / script-function name the ext calls (dc_audit_tick checks them).",
           "static const struct { uint64_t sid; const char *name; unsigned char late; } DC_NAMES[] = {"]
    for n, h in rows:
        out.append('    {0x%016xULL, "%s", %d},' % (h, n, 1 if n.startswith(LATE) else 0))
    out.append("};")
    out.append("#define DC_NAMES_N (sizeof DC_NAMES / sizeof DC_NAMES[0])")
    return "\n".join(out) + "\n"


def main():
    txt = render(collect())
    if "--check" in sys.argv:
        cur = open(OUT, encoding="latin-1", newline="").read() if os.path.exists(OUT) else ""
        if cur.replace("\r\n", "\n") != txt:
            print("dcnames.h is out of date: run python tools/ext/gen_dcnames.py")
            return 1
        print("dcnames.h up to date (%d names)" % len(collect()))
        return 0
    open(OUT, "w", encoding="latin-1", newline="\n").write(txt)
    print("wrote %s (%d names)" % (OUT, len(collect())))
    return 0


if __name__ == "__main__":
    sys.exit(main())
