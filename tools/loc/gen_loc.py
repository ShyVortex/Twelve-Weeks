"""tools/loc/<code>/*.txt -> tools/ext/loc_<code>.h (the ext's translation table) + re/loc/<code>-review.md (every string, grouped).

  python gen_loc.py [pl]

Source format: see locdata.py. The probe ids for the language detection (text ids whose English and <engine> wording differ) are
taken from the game's own text tables (text2/eng.common vs text2/<engine>.common in core.psarc) the first time and cached in
<code>.probes.json. The review file marks every source string that was not found in the ext / widget / winmm / game text sources.
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
TOOLS = os.path.dirname(HERE)
ROOT = os.path.dirname(TOOLS)
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(TOOLS, "features"))
import locdata  # noqa: E402
import loc_tables  # noqa: E402

GAME = os.environ.get("T2_GAME", "C:/Games/The Last of Us Part II Remastered")
ENGINE = {code: eng for eng, code in loc_tables.LANGS.items()}


def cstr(s):
    out = []
    for ch in s:
        out.append({"\\": "\\\\", '"': '\\"', "\n": "\\n", "\t": "\\t"}.get(ch, ch))
    return '"' + "".join(out) + '"'


def probes(code):
    cache = os.path.join(HERE, code + ".probes.json")
    if os.path.exists(cache):
        return json.load(open(cache, encoding="utf-8"))
    sys.path.insert(0, os.path.join(TOOLS, "part1"))
    import p1_archive
    import tempfile
    import sys as _t2s, os as _t2o; _t2s.path.append(_t2o.path.normpath(_t2o.path.join(_t2o.path.dirname(_t2o.path.abspath(__file__)), "..")))  # noqa: E402
    import t2rtmp  # noqa: F401  (temp hygiene: tools/t2rtmp.py)
    arch = p1_archive.Psarc(os.path.join(GAME, "build", "pc", "main", "core.psarc"))
    d = tempfile.mkdtemp()
    tabs = {}
    for lang in ("eng", ENGINE[code]):
        p = os.path.join(d, lang + ".common")
        open(p, "wb").write(arch.get("text2/%s.common" % lang))
        tabs[lang] = loc_tables.load(p)
    en, pl = tabs["eng"], tabs[ENGINE[code]]
    out = []
    for sid in sorted(en):
        a, b = en[sid], pl.get(sid)
        if b is None or a == b or not (4 <= len(a) <= 24) or not (4 <= len(b) <= 40):
            continue
        try:
            sa, sb = a.decode("ascii"), b.decode("utf-8")
        except UnicodeDecodeError:
            continue
        if not sa.replace(" ", "").isalpha() or any(c in sb for c in "<|%{") or sa.lower() == sb.lower():
            continue
        out.append({"sid": sid, "en": sa, "tr": sb})
        if len(out) >= 10:
            break
    json.dump(out, open(cache, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    return out


def main(code):
    rows = locdata.load(code)
    pr = probes(code)
    U = code.upper()
    h = ["// generated by tools/loc/gen_loc.py from tools/loc/%s/*.txt - do not edit" % code,
         "#ifndef LOC_%s_H" % U, "#define LOC_%s_H" % U,
         "#ifndef LOC_TYPES", "#define LOC_TYPES", "typedef struct { const char *en, *tr; } loc_ent_t;",
         "typedef struct { unsigned long long sid; const char *en, *tr; } loc_probe_t;", "#endif",
         "static const loc_ent_t LOC_%s[] = {" % U]
    for g, k, v, rk, rv in rows:
        h.append("    {%s, %s}," % (cstr(k), cstr(v)))
    h.append("};")
    h.append("#define LOC_%s_N %d" % (U, len(rows)))
    h.append("static const loc_probe_t LOC_%s_PROBES[] = {" % U)
    for p in pr:
        h.append("    {0x%016xULL, %s, %s}," % (p["sid"], cstr(p["en"]), cstr(p["tr"])))
    h.append("};")
    h.append("#define LOC_%s_NPROBES %d" % (U, len(pr)))
    h.append("#endif")
    open(os.path.join(TOOLS, "ext", "loc_%s.h" % code), "w", encoding="utf-8", newline="\n").write("\n".join(h) + "\n")
    # review file (verify: is the key in a source?)
    import loc_verify
    found = loc_verify.verify([k for _, k, _, _, _ in rows])
    os.makedirs(os.path.join(ROOT, "re", "loc"), exist_ok=True)
    md = ["# Polish translation review (%s)" % code, "",
          "Source: `tools/loc/%s/*.txt` (edit there, then `python tools/loc/gen_loc.py %s`; the ext header `tools/ext/loc_%s.h` is regenerated). "
          "%d strings. How it works: the ext translates every English string of the mod just before it is shown (exact text, or a text with "
          "numbers / names that matches a `%%d` / `%%s` pattern; rich-text tags and line breaks split a text into pieces). In a Polish text "
          "`{1}` = the first captured value of the English pattern (number or name), `{N|a|b|c}` = Polish plural of number N (1 / 2-4 / 5+). "
          "Texts marked `*` were not found literally in the sources (they are composed at run time, copied from a server / winmm string or rewritten game "
          "text) - check them in game." % (code, code, code, len(rows)), "",
          "Checklist (ticked = every string of it is in the tables below; group names in brackets):", "",
          "- [x] Loading screens: map names, tips, mission lines [Maps, Match flow - loading screen tips, Match flow - find match, vote, loading screen]",
          "- [x] Gear Up flow: classes / loadouts, weapon and purchasable names + descriptions, stat labels, LP counters, A/D TO SELECT, level hints, warnings [Gear Up - ...]",
          "- [x] Skills: names, every level description, details panel, picker rows [Survival skills - ...]",
          "- [x] Boosters [Match flow - one-use boosters]",
          "- [x] Map names everywhere (vote, loading, banners) [Maps]",
          "- [x] Crafting recipe cards and item descriptions our build rewrites (Polish table gets the multiplayer meaning, not the SP text), impaled prompt [Game text table strings our build REWRITES]",
          "- [x] Clan pages: first launch, choose side, faction texts, events, missions, rewards, post-match, clan win / loss [Clan - ...]",
          "- [x] Match flow pages: vote, countdowns, booster, loadout [Match flow - ...]",
          "- [x] Death screen and spectate bar, death tips [Death screen and spectating, Killed-by card, Death screen tips]",
          "- [x] Scoreboard / end banners (VICTORY, DEFEAT, WLF WIN ...), honours [Match flow - banners, Match honours]",
          "- [x] HUD messages and prompts (revive / execute / shiv / buy / box), award popups [Prompts, hints and HUD messages, Award popups ...]",
          "- [x] Store / buy menu [Gear Up - weapon names (ARMOUR, SHOP, %s AMMO ...), weapon upgrades]",
          "- [x] Options rows, name entry [Options and name entry, Options menu rows added by the mod revival]",
          "- [x] Server messages (daemon 0x11 notes, ban, version mismatch) and winmm connection messages [Match flow - connection and server messages]",
          "- [x] Interrogation mode [Interrogation mode]",
          "- [x] Static widget labels baked by tools/features/*widgets*.py (moved to text ciphers, all languages) - same keys as above", "",
          "Deliberately left in English (reason): player names, clan tags, map vote names typed by players (not ours to translate); the brand names "
          "THE LAST OF US TWELVE WEEKS / TWELVE WEEKS / MULTIPLAYER button; weapon names that are proper names (SPECTER, ENFORCER, EL DIABLO, MPX5, "
          "VEPR, GALIL); developer overlays and log lines (CAM EDIT, `xlog`, spawn-view labels); messages that are compiled out (T2R_NO_MSG: "
          "'Listen mode recharging', 'Being revived...' etc. have entries but never show); a host's free-text T2R_NOTE; the launcher's console "
          "messages (Play.ps1 / Play.bat, outside the game); winmm's own raw text draws that call the text routine directly with composed "
          "text (radar, score bar) - those cannot be translated by this layer; the other 22 game languages (their tables only get the English "
          "text for our labels so nothing is blank).", ""]
    cur = None
    esc = lambda s: s.replace("|", "\\|").replace("\n", " ")
    for (g, k, v, rk, rv), ok in zip(rows, found):
        if g != cur:
            cur = g
            md += ["", "## " + g, "", "| English | Polish |", "|---|---|"]
        md.append("| %s%s | %s |" % (esc(k), "" if ok else " *", esc(v)))
    open(os.path.join(ROOT, "re", "loc", "%s-review.md" % code), "w", encoding="utf-8", newline="\n").write("\n".join(md) + "\n")
    print("loc_%s.h: %d entries, %d probes, %d not found literally in the sources" % (code, len(rows), len(pr), sum(1 for f in found if not f)))


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "pl")
