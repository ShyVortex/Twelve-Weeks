"""tools/modes.json is THE list of FIND MATCH game modes (a new mode = a new row). Everything derives from it:
  tools/modeq.py                      daemon queues (MODES names, count of modes)
  tools/features/modepick_widgets.py  the mode box on the MP menu (one native button per mode, box sized to N)
  tools/ext/modes.h                   generated by this script: MODE_N + the table the ext page uses (python tools/gen_modes.py)
`key` must be the name tools/interrogation.py / the daemon knows for the mode (supply-raid, interrogation)."""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))


def load():
    return json.load(open(os.path.join(HERE, "modes.json"), encoding="utf-8"))


def header():
    m = load()
    assert [e["id"] for e in m] == list(range(len(m)))
    out = ["// GENERATED by tools/gen_modes.py from tools/modes.json - do not edit", "#define MODE_N %d" % len(m),
           "static const struct { const char *key, *label; } MODE_TAB[MODE_N] = {"]
    out += ['    {"%s", "%s"},' % (e["key"], e["label"]) for e in m]
    out.append("};")
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    open(os.path.join(HERE, "ext", "modes.h"), "w", newline="").write(header())
