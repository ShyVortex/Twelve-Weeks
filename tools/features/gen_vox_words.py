"""vox_words.h: a wording hash per line of vox_lines.h / vox_lines_female.h (never repeat a WORDING within a window, across voices
and speakers). The text is the subtitle in the generated header's trailing comment; whistles / empty text hash to 0 (exempt).
Run: python tools/features/gen_vox_words.py"""
import re, os
D = os.path.join(os.path.dirname(__file__), '..', 'ext')
def fnv(s):
    h = 0x811c9dc5
    for c in s.encode():
        h = ((h ^ c) * 0x01000193) & 0xffffffff
    return h or 1
def words(fn, arr):
    out = []; inarr = False
    for ln in open(os.path.join(D, fn), encoding='utf-8'):
        if ('static const vx_line_t %s[]' % arr) in ln: inarr = True; continue
        if inarr and ln.startswith('};'): break
        if inarr and ln.lstrip().startswith('{{'):
            m = re.search(r'//\s+t2r-vox-\S+\s+(\S+):\s?(.*)$', ln)
            t = m.group(2).strip() if m else ''
            t = re.sub(r'\([^)]*\)|\{[^}]*\}', ' ', t)          # (whistle) / (to self) / {breath} markers
            k = re.sub(r'[^a-z0-9]', '', t.lower())
            out.append(fnv(k) if k else 0)
    return out
o = ['// generated by tools/features/gen_vox_words.py - wording hash per line (0 = no words / exempt)']
for fn, arr, nm in (('vox_lines.h', 'VX_LINES', 'VX_WORD'), ('vox_lines_female.h', 'VXF_LINES', 'VXF_WORD')):
    w = words(fn, arr)
    o.append('static const uint32_t %s[] = {%s};' % (nm, ', '.join('0x%08x' % x for x in w)))
    print(nm, len(w), sum(1 for x in w if not x), 'exempt')
open(os.path.join(D, 'vox_words.h'), 'w').write('\n'.join(o) + '\n')
